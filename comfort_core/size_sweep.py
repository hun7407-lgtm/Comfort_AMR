"""Comfort Space SIZE as an experimental factor.

Pure Python. Used by the Stage 1 sweep (scripts/stage1_sweep.sh), the
Stage 2 size ladder (scripts/stage2_make_conditions.py) and the Stage 3
validation (scripts/stage3_run.sh), so the three cannot disagree about
what "B3-O at 1.0 m" means.

A size condition is a scenario overlay -- only the `scenario` and
`comfort_space` sections, exactly what comfort_core.config allows -- so
the campaign config it is run on (people, walks, missions, timing, map,
Nav2) is untouched and identical across every size and both policies.

    static_r1.00   policy static,            static_radius 1.00
    b3o_r1.00      policy state_directional, aisle_scaling target 1.00

For B3-O "size" is the moving-front extent at the reference speed
(1.20 m unscaled). The whole geometry is multiplied by size / 1.20, so
front/side/rear and the three states keep their relations; see
comfort_core.comfort_space._scaling. With floor_m 0.0 the only floor
left is comfort_space.min_radius, which is a property of the person, not
of the sweep.

> Engineering sweep over a configurable parameter. None of these sizes
> is an experimentally validated comfort distance.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Tuple

import yaml

from comfort_core.config import load_config, resolve_path

# User-facing names. The code keeps `state_directional` / `b3d` for
# compatibility with every recorded batch; the reports say B3-O.
KIND_LABEL = {"static": "Static", "b3o": "B3-O"}
KIND_POLICY = {"static": "static", "b3o": "state_directional"}
POLICY_KIND = {v: k for k, v in KIND_POLICY.items()}

# The default Stage 1 sweep, metres.
DEFAULT_SIZES: Tuple[float, ...] = (0.8, 1.0, 1.2, 1.4, 1.6)

_NAME = re.compile(r"^(static|b3o)_r(\d+\.\d{2})$")


def condition_name(kind: str, size_m: float) -> str:
    if kind not in KIND_POLICY:
        raise ValueError(f"kind must be one of {sorted(KIND_POLICY)}, not {kind!r}")
    return f"{kind}_r{size_m:.2f}"


def parse_condition(name: str) -> Optional[Tuple[str, float]]:
    """(kind, size_m) from a condition name or path, None if it is not one."""
    # Not Path.stem: "b3o_r1.00" has no suffix, and .stem would eat ".00".
    text = Path(str(name)).name
    if text.endswith((".yaml", ".yml")):
        text = text.rsplit(".", 1)[0]
    m = _NAME.match(text)
    if not m:
        return None
    return m.group(1), float(m.group(2))


def condition_overlay(kind: str, size_m: float,
                      stage: str = "Stage 1") -> Dict[str, Any]:
    """The scenario YAML for one size condition, as a dict."""
    name = condition_name(kind, size_m)
    if kind == "static":
        return {
            "scenario": {"name": name,
                         "label": f"Static Comfort Space {size_m:.2f} m"},
            "comfort_space": {"policy": "static",
                              "static_radius": round(float(size_m), 4)},
        }
    return {
        "scenario": {"name": name,
                     "label": (f"B3-O Dynamic Comfort Space, size {size_m:.2f} m "
                               f"(moving front at the reference speed)")},
        "comfort_space": {
            "policy": "state_directional",
            "aisle_scaling": {
                "enabled": True,
                "target_size_m": round(float(size_m), 4),
                # Pure multiplication: comfort_space.min_radius is the
                # only floor. The default floor (min_radius itself) would
                # pull every extent TOWARD 0.30 m instead of scaling it,
                # and 0.80 m would come out as 0.90 m.
                "floor_m": 0.0,
            },
        },
    }


_HEADER = """\
# {stage} size condition: {label} Comfort Space, size {size:.2f} m.
#
# GENERATED by scripts/make_size_conditions.py -- regenerate rather than
# hand-edit. ONLY `scenario` and `comfort_space` appear here, so the
# campaign config this is run on (people, walks, missions, start times,
# map, Nav2 parameters, safety layer) is byte-identical across every
# size and both policies. See comfort_core/size_sweep.py.
#
{how}
#
# > Engineering sweep over a configurable parameter. Not an
# > experimentally validated comfort distance, and not a safety
# > distance: the protective field is sized separately and is never
# > changed with this.
"""

_HOW = {
    "static": "# One round space of this radius for everybody, whatever they do.",
    "b3o": ("# The whole directional geometry (station_engaged / stationary /\n"
            "# moving, front / side / rear, the speed mapping and its clips) is\n"
            "# multiplied by size / 1.20, 1.20 m being the unscaled moving-front\n"
            "# extent at the reference speed. Ratios and state relations are\n"
            "# those of configs/common.yaml comfort_space.directional; only the\n"
            "# comfort_space.min_radius floor remains."),
}


def write_condition(out_dir: str | Path, kind: str, size_m: float,
                    stage: str = "Stage 1") -> Path:
    out_dir = resolve_path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{condition_name(kind, size_m)}.yaml"
    body = yaml.safe_dump(condition_overlay(kind, size_m, stage),
                          sort_keys=False, default_flow_style=False)
    path.write_text(_HEADER.format(stage=stage, label=KIND_LABEL[kind],
                                   size=size_m, how=_HOW[kind]) + "\n" + body,
                    encoding="utf-8")
    return path


def write_conditions(out_dir: str | Path, sizes: Iterable[float],
                     kinds: Iterable[str] = ("static", "b3o"),
                     stage: str = "Stage 1") -> List[Path]:
    return [write_condition(out_dir, kind, float(size), stage)
            for size in sizes for kind in kinds]


def applied_geometry(condition_path: str | Path,
                     campaign_config: str | Path) -> Dict[str, Any]:
    """What the condition comes out as, in metres, on a given campaign config."""
    from comfort_core.comfort_space import geometry_record
    cfg = load_config(scenario=str(condition_path),
                      common_path=str(campaign_config))
    rec = geometry_record(cfg)
    rec["condition"] = Path(condition_path).stem
    rec["policy"] = cfg["comfort_space"]["policy"]
    return rec


def ladder(top_m: float, step_m: float, count: int,
           floor_m: float = 0.0) -> List[float]:
    """top, top - step, top - 2 step, ... (`count` values, none below floor).

    A descending size ladder. Rounded to the centimetre so the
    condition names are stable.
    """
    if step_m <= 0.0:
        raise ValueError("comfort_step_m must be positive")
    out = []
    for i in range(int(count)):
        v = round(top_m - i * step_m, 2)
        if v < floor_m - 1e-9:
            break
        out.append(v)
    return out
