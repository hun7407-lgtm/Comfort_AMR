#!/usr/bin/env python3
"""Write a one-person Comfort Space config for the real corridor.

    make_comfort_cfg.py <x> <y> <state> [out]

The position is in the map frame, which a freshly started slam_toolbox puts
at the robot's current pose: +x straight ahead, +y to its left.

Only the STATE changes between the three captures. The person stands in one
place and the policy decides how much room that state needs:

    moving           1.20 m
    stationary       0.90 m
    station_engaged  0.60 m

The corridor is 2.1 m wide, so this is not a cosmetic difference -- at 0.90 m
the Comfort Space spans the whole corridor and there is no way past.
"""
import sys

x, y, state = float(sys.argv[1]), float(sys.argv[2]), sys.argv[3]
out = sys.argv[4] if len(sys.argv) > 4 else "/home/clabil/comfort/configs/real_corridor.yaml"
assert state in ("moving", "stationary", "station_engaged"), state

open(out, "w").write(f"""# Generated by make_comfort_cfg.py -- do not hand edit.
base: configs/common.yaml

nav2:
  # The map SLAM built of this corridor with nobody in it. The Comfort Space
  # mask must share this grid cell for cell, or the painted radius is not the
  # configured radius.
  map: /home/clabil/maps/states_clean.yaml

amr:
  # Measured on the real robot. The simulated AMR is 0.70 x 0.48.
  footprint_length: 0.864
  footprint_width: 0.570

comfort_space:
  # state_adaptive is the only policy under which the three states differ.
  # Under `static` all three would paint the same circle.
  policy: state_adaptive
  # Ellipse, so a walker's space is longer along their line of travel than
  # across it -- that is where they are about to be. Only `moving` is
  # stretched; a standing person stays round either way.
  #
  # The ellipse is symmetric about the person, so it reaches as far behind
  # them as in front. That is the model as designed, not an artefact: a
  # costmap has no time axis, and deciding which half to keep needs the
  # prediction that comfort_core/evasion.py does with one.
  shape: ellipse

  # Radii scaled to THIS corridor, which is 2.2 m wide. The values in
  # configs/common.yaml (0.60 / 0.90 / 1.20) were set for the simulated
  # 3.9 m corridor and the 12 m factory bay, and carrying them over
  # unchanged meant one person closed the corridor completely.
  #
  # Derived from the measured empty costmap, not guessed. The band the
  # robot's CENTRE may occupy here is 1.35-1.45 m wide. With a person
  # standing against the wall at y -0.84, the gap left for the robot is
  #
  #     gap = 0.50 - (-0.84 + r + 0.285)
  #
  # so r 0.90 leaves 0.16 m, r 0.75 leaves 0.31 m, r 0.60 leaves 0.46 m.
  # These values keep someone who has stood aside passable with a workable
  # margin -- about x0.65 of the simulation's numbers.
  #
  # A person in the MIDDLE of this corridor cannot be passed at any radius
  # worth the name: 2.2 m minus a 0.5 m person minus a 0.57 m robot leaves
  # 1.13 m, split in two. At r 0.40 the gap is already 0.04 m and at 0.50 it
  # is zero. That is geometry, not policy, and it is what the yield gate is
  # for -- the robot should stop, not squeeze past.
  state_radius:
    moving: 0.75
    stationary: 0.60
    station_engaged: 0.45

  # Speed scaling OFF, deliberately.
  #
  # With it on, a `moving` person's radius is interpolated from their
  # measured speed down to the resting radius, and these captures declare
  # the state instead of measuring it -- the tracker sees no TF for this
  # person, so their speed is 0 and `moving` collapses to 0.90 m, the same
  # as `stationary`. Switching it off makes `moving` mean state_radius.moving
  # flat, which is what the three captures are meant to show. Turn it back on
  # once the person's position comes from detection and the speed is real.
  dynamic:
    enabled: false

humans:
  state_source: ground_truth
  # The two humans common.yaml places in the simulated bay.
  a:
    enabled: false
  b:
    enabled: false
  character:
    enabled: false
  p:
    position: [{x}, {y}]
    state: {state}
""")
print(f"{out}: person at ({x}, {y}) state={state}")
