#!/usr/bin/env python3
"""Final Stage 1-3 experiments (rev. 2026-11-25): configs and run manifests.

    python3 scripts/final_plan.py seeds --seeds 1-200          # per-seed run configs
    python3 scripts/final_plan.py stage1-coarse                # B1 + B2 0.80..1.60, seeds 1-100
    python3 scripts/final_plan.py stage1-fine --sizes 0.85,0.90,0.95
    python3 scripts/final_plan.py smoke                        # 3 seeds, B1/B2 for the pipeline check
    python3 scripts/final_plan.py stage3                       # B1/B2/B3-O, holdout seeds 101-200

Plain Python 3. Writes only under configs/final/ and the batch folder's
manifest; never touches an earlier batch.

What is fixed for EVERY trial (configs/final/seeds/s<N>.yaml):
    base       configs/campaigns/cross/campaign_h8_a3_cross_s<N>.yaml  (8 people, AMR 1/2/3,
               the seed's worker exchanges / walker speeds / start times)
    navigation frozen Stage 1 setting: Comfort costmap buffer 0.10 m
               (configs/frozen/navigation_requirements.yaml); safety layer, collision
               monitor, footprint, inflation and Nav2 parameters unchanged from common.yaml
    Nav2 only  AMR 1's comfort gate may only HOLD (zero the command). The three
               manoeuvres that wrote their own velocity commands are off:
               comfort_space.yield.evade, recovery.backoff, recovery.off_lane.
               a1/a2 were already Nav2-only. Nav2's own recoveries stay.
    recording  fixed orthographic top view CAM01_TOP (whole bay) + per-frame pose log.

What a condition changes (configs/final/conditions/*.yaml): comfort_space policy
and size only.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from comfort_core.selection import frozen_navigation  # noqa: E402

TAG = "261125"
CFG = PROJECT_ROOT / "configs" / "final"
SEEDS_DIR = CFG / "seeds"
COND_DIR = CFG / "conditions"
BATCH = PROJECT_ROOT / "results" / "batches"
STAGE1 = BATCH / f"{TAG}_final_stage1"
CROSS = "configs/campaigns/cross/campaign_h8_a3_cross_s{seed}.yaml"
COARSE = [0.80, 1.00, 1.20, 1.40, 1.60]
TOP_CAM = {"ortho": {"centre": [0.0, 0.0], "width_m": 30.0}}      # = CAM01_TOP of the paper videos
HEAD = ("# GENERATED by scripts/final_plan.py -- regenerate, do not hand-edit.\n"
        "# Final Stage 1-3 experiments (rev. 2026-11-25).\n")


def parse_seeds(spec: str):
    out = []
    for part in spec.split(","):
        if "-" in part:
            a, b = part.split("-")
            out += list(range(int(a), int(b) + 1))
        elif part.strip():
            out.append(int(part))
    return out


def size_tag(r: float) -> str:
    return f"{int(round(r * 100)):03d}"


def write_seed(seed: int) -> Path:
    base = PROJECT_ROOT / CROSS.format(seed=seed)
    if not base.exists():
        raise SystemExit(f"[ERROR] {base} missing: python3 scripts/make_cross_campaign.py --seeds {seed}")
    buf = float(frozen_navigation()["comfort_buffer_m"])
    p = SEEDS_DIR / f"s{seed}.yaml"
    p.write_text(HEAD + yaml.safe_dump({
        "base": CROSS.format(seed=seed),
        "comfort_space": {
            "costmap": {"buffer_width": buf},
            "yield": {"evade": {"enabled": False}},
            # drawing only (isaac_sim/utils/comfort_viz.py: visual prims, no collider)
            "visualization": {"enabled": True},
        },
        "recovery": {"backoff": {"enabled": False}, "off_lane": {"enabled": False}},
        "recording": {"version": f"final_{TAG}", "fps": 10, "resolution": [1920, 1080],
                      "label": False, "pose_log": True, "camera": TOP_CAM},
    }, sort_keys=False))
    return p


def write_condition(name: str, label: str, cs: dict) -> Path:
    COND_DIR.mkdir(parents=True, exist_ok=True)
    p = COND_DIR / f"{name}.yaml"
    p.write_text(HEAD + yaml.safe_dump({"scenario": {"name": name, "label": label},
                                        "comfort_space": cs}, sort_keys=False))
    return p


def b1() -> Path:
    return write_condition("B1", "B1 No Comfort Space (safety layer only)", {"policy": "none"})


def b2(r: float) -> Path:
    return write_condition(f"B2_r{size_tag(r)}", f"B2 Static Comfort Space r {r:.2f} m",
                           {"policy": "static", "static_radius": round(r, 3)})


LEVELS = {"LOWER": 0.0, "MID": 0.5, "UPPER": 1.0}
STATE_KEYS = ("station_engaged", "stationary", "moving")
DIRS = ("front", "side", "rear")


def stage3(seeds) -> int:
    """Stage 3 conditions from the Stage 1 upper bound and the Stage 2 proxy.

    R(H,d) = R_lower(H,d) + alpha * (R_nav_upper - R_lower(H,d)), alpha = 0 / 0.5 / 1
    (LOWER / MID / UPPER); main B3-O = MID. An INSUFFICIENT cell takes the largest
    available cell of the same state, else the largest of all (conservative).
    B2 = one static radius = max over cells of R_MID, capped at R_nav_upper.
    """
    import json
    ub = json.loads((STAGE1 / "analysis" / "stage1_upper_bound.json").read_text())
    if ub.get("partial"):
        raise SystemExit("[ERROR] Stage 1 analysis is marked partial; finish Stage 1 first")
    upper = ub["decision"]["R_nav_upper_m"]
    if upper is None:
        raise SystemExit("[ERROR] Stage 1 gave no R_nav_upper")
    s2 = json.loads((BATCH / f"{TAG}_final_stage2_proxy" / "stage2_provisional_lower_bound.json").read_text())
    assert s2["source"] == "SIMULATION_DERIVED_PROVISIONAL"
    cells = {k: v["R_lower_proxy_m"] for k, v in s2["R_lower_proxy"].items()}
    filled = {}
    for st_ in STATE_KEYS:
        same = [v for k, v in cells.items() if k.startswith(st_ + "|") and v is not None]
        for d in DIRS:
            v = cells.get(f"{st_}|{d}")
            src = "proxy"
            if v is None:
                v, src = (max(same), "same-state max") if same else (max(x for x in cells.values() if x is not None),
                                                                    "overall max")
            filled[f"{st_}|{d}"] = {"R_lower": min(v, upper), "fill": src, "capped_at_upper": v > upper}
    sel = {"R_nav_upper_m": upper, "levels": {}, "cells": filled}
    conds = {}
    for lvl, a in LEVELS.items():
        R = {k: round(c["R_lower"] + a * (upper - c["R_lower"]), 3) for k, c in filled.items()}
        sel["levels"][lvl] = {"alpha": a, "R": R}
        directional = {}
        for st_ in ("station_engaged", "stationary"):
            directional[st_] = {"front_m": R[f"{st_}|front"], "side_m": R[f"{st_}|side"],
                                "rear_m": R[f"{st_}|rear"], "heading_source": "body"}
        flat = lambda r: {"intercept_m": r, "gain_s": 0.0, "min_m": r, "max_m": r}  # noqa: E731
        directional["moving"] = {"heading_source": "velocity", "heading_min_speed_mps": 0.10,
                                 "speed_mapping": {"front": flat(R["moving|front"]), "side": flat(R["moving|side"]),
                                                   "rear": flat(R["moving|rear"])}}
        conds[lvl] = write_condition(f"B3O_{lvl}", f"B3-O Adaptive Comfort Space, {lvl} (alpha {a})",
                                     {"policy": "state_directional", "directional": directional,
                                      "aisle_scaling": {"enabled": False}})
    r_b2 = round(min(max(sel["levels"]["MID"]["R"].values()), upper), 3)
    sel["B2_static_m"] = r_b2
    b2c = write_condition(f"B2_S3_r{size_tag(r_b2)}", f"B2 Static Comfort Space r {r_b2:.2f} m (Stage 3)",
                          {"policy": "static", "static_radius": r_b2})
    out = BATCH / f"{TAG}_final_stage3"
    out.mkdir(parents=True, exist_ok=True)
    (out / "stage3_selection.json").write_text(json.dumps(sel, indent=1))
    for s in seeds:
        write_seed(s)
    main_rows = [(f"s{s:03d}_{c.stem}", s, rel(c), rel(SEEDS_DIR / f"s{s}.yaml"))
                 for s in seeds for c in (b1(), b2c, conds["MID"])]
    manifest(out / "main", main_rows, "Stage 3 main: B1 / B2 / B3-O MID, holdout seeds")
    sens_rows = [(f"s{s:03d}_{c.stem}", s, rel(c), rel(SEEDS_DIR / f"s{s}.yaml"))
                 for s in seeds for c in (conds["LOWER"], conds["UPPER"])]
    manifest(out / "sensitivity", sens_rows, "Stage 3 sensitivity: B3-O LOWER / UPPER, holdout seeds")
    print(json.dumps(sel, indent=1))
    return 0


def manifest(out: Path, rows, note: str) -> None:
    out.mkdir(parents=True, exist_ok=True)
    m = out / "manifest.tsv"
    if m.exists():
        old = [l for l in m.read_text().splitlines() if l and not l.startswith("#")]
        new = ["\t".join(map(str, r)) for r in rows]
        if old != new[:len(old)]:
            raise SystemExit(f"[ERROR] {m} exists with different trials; refusing to overwrite")
    lines = [f"# {note}", "# trial_id\tseed\tcondition\tconfig"] + ["\t".join(map(str, r)) for r in rows]
    m.write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} trials -> {m.relative_to(PROJECT_ROOT)}")


def rel(p: Path) -> str:
    return str(p.relative_to(PROJECT_ROOT))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("what", choices=["seeds", "stage1-coarse", "stage1-fine", "smoke", "stage3"])
    ap.add_argument("--seeds", default="1-100")
    ap.add_argument("--sizes", default="")
    ap.add_argument("--out", default="")
    args = ap.parse_args()
    SEEDS_DIR.mkdir(parents=True, exist_ok=True)
    seeds = parse_seeds(args.seeds)
    if args.what == "seeds":
        for s in seeds:
            write_seed(s)
        print(f"{len(seeds)} seed configs -> {rel(SEEDS_DIR)}")
        return 0
    for s in seeds:
        write_seed(s)
    if args.what == "stage3":
        return stage3(parse_seeds(args.seeds if args.seeds != "1-100" else "101-200"))
    if args.what == "smoke":
        conds = [b1(), b2(1.20)]
        rows = [(f"smoke_s{s:03d}_{c.stem}", s, rel(c), rel(SEEDS_DIR / f"s{s}.yaml"))
                for s in (2, 5, 12) for c in conds]
        manifest(Path(args.out) if args.out else BATCH / f"{TAG}_final_smoke", rows, "smoke: pipeline check")
        return 0
    if args.what == "stage1-coarse":
        conds = [b1()] + [b2(r) for r in COARSE]
        note = "Stage 1 coarse: B1 + B2 Static 0.80/1.00/1.20/1.40/1.60, seeds interleaved"
    else:
        sizes = [float(v) for v in args.sizes.split(",") if v]
        if not sizes:
            raise SystemExit("--sizes required")
        conds = [b2(r) for r in sizes]
        note = f"Stage 1 fine: B2 Static {', '.join(f'{r:.2f}' for r in sizes)}"
    rows = [(f"s{s:03d}_{c.stem}", s, rel(c), rel(SEEDS_DIR / f"s{s}.yaml")) for s in seeds for c in conds]
    out = Path(args.out) if args.out else STAGE1 / ("coarse" if args.what == "stage1-coarse" else "fine")
    manifest(out, rows, note)
    return 0


if __name__ == "__main__":
    sys.exit(main())
