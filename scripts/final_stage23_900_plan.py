CFG = PROJECT_ROOT / "configs" / "final_nav2only_stage23_900" / "stage23_900.yaml"
TAG = "# GENERATED by scripts/final_stage23_900_plan.py -- do not hand-edit.\n"
STAGE3_RECORDING = {"version": "stage23_900", "fps": 10, "resolution": [1920, 1080], "label": False,
                    "pose_log": True, "camera": {"ortho": {"centre": [0.0, 0.0], "width_m": 30.0}}}


def sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()[:16]


def atag(a) -> str:
    return f"{float(a):.2f}"


def cname(c) -> str:
    return c if str(c).startswith("B2") else f"S3_a{atag(c)}"


def rng(*parts) -> random.Random:
    return random.Random("stage23_900|" + "|".join(str(p) for p in parts))


def jit(r: random.Random, half: float) -> float:
    return round(r.uniform(-half, half), 4)


# ------------------------------------------------------------- Stage 2 envs
def static_env(ctx: str, c: dict, g: dict, width: float, seed: int, J: dict) -> tuple:
    r = rng("stage2", ctx, seed)
    jx, jf, jp, js = (jit(r, J["person_x_m"]), jit(r, J["facing_deg"]), jit(r, J["path_offset_m"]),
                      jit(r, J["start_x_m"]))
    half = width / 2.0
    station = None
    if c.get("station"):
        st = g["station"]
        depth = float(st["size"][1])
        sy = round(half - depth / 2.0, 4)                    # back on the +y wall
        py = round(sy - depth / 2.0 - float(st["stand_gap_m"]), 4)
        station = {"position": [jx, sy]}
    else:
        py = round(half - g["person_wall_gap_m"], 4)
    ly = round(py - (g["path_offset_m"] + jp), 4)
    f = ((facing_deg(c["context"], -90.0) + jf + 180.0) % 360.0) - 180.0
    ov = {"corridor": {"width": width, "length": g["corridor_length_m"], "center": [0.0, 0.0]},
          "humans": {"a": {"position": [jx, py], "state": c["state"], "facing_deg": round(f, 3)},
                     "b": {"enabled": False}, "c": {"enabled": False}},
          "navigation": {"start": [round(g["start_x"] + js, 4), ly], "goal": [round(g["goal_x"] + js, 4), ly]},
          "stations": ({"size": list(g["station"]["size"]), "equipment": {"enabled": False},
                        "a": station, "b": {"enabled": False}} if station
                       else {"a": {"enabled": False}, "b": {"enabled": False}})}
    meta = {"width_m": width, "facing_deg": round(f, 3), "jitter": {"person_x": jx, "facing_deg": jf,
                                                                     "path_offset": jp, "start_x": js},
            "station": station}
    return ov, meta


def moving_env(ctx: str, m: dict, width: float, gap: float, seed: int, J: dict) -> tuple:
    r = rng("stage2", ctx, seed)
    jw, jy, ja = jit(r, J["walker_start_x_m"]), jit(r, J["walker_lane_y_m"]), jit(r, J["amr_start_x_m"])
    c, s = float(m["lane_centre_y"]), float(m["human_side"])
    hy, ay = round(c + s * gap / 2.0 + jy, 4), round(c - s * gap / 2.0, 4)
    ov = {"corridor": {"width": width, "length": m["corridor_length_m"], "center": [0.0, 0.0]},
          "humans": {"a": {"position": [round(m["walker_start_x"] + jw, 4), hy], "state": "moving",
                           "route": [[m["walker_end_x"], hy]], "avoid_robot": False},
                     "b": {"enabled": False}, "c": {"enabled": False}},
          "navigation": {"start": [round(m["amr_start_x"] + ja, 4), ay], "goal": [round(m["amr_goal_x"] + ja, 4), ay]},
          "stations": {"a": {"enabled": False}, "b": {"enabled": False}}}
    meta = {"width_m": width, "lane_gap_m": gap, "human_lane_y": hy, "amr_lane_y": ay,
            "jitter": {"walker_start_x": jw, "walker_lane_y": jy, "amr_start_x": ja}}
    return ov, meta


def stage2_env_text(S, ctx, c, gid, seed, ov, control) -> str:
    doc = {"base": "configs/common.yaml",
           "scenario_meta": {"scenario_id": f"{S['version']}_{ctx}_{gid}_s{seed:03d}",
                             "stage": f"Stage 2 {S['version']}", "label": c["label"], "seed": seed,
                             "human_count": 1, "amr_count": 1, "aisle_width_m": ov["corridor"]["width"]},
           **ov, "fleet": {"enabled": False}}
    for k, v in control.items():
        doc[k] = {**doc[k], **v} if k == "navigation" else v
    return TAG + f"# {c['label']} -- {gid}, seed {seed}\n" + yaml.safe_dump(doc, sort_keys=False)


def stage2_geometries(S, phase, ctx, c):
    """[(gid, builder(seed) -> (ov, meta))] for this phase."""
    G = S["stage2"]["geometry"]
    J = S["stage2"]["jitter"]
    P = S["stage2"]["pilot"]
    fz = (S.get("frozen") or {}).get(ctx)
    if c["state"] == "moving":
        if phase == "s2pilot":
            gaps = [float(x) for x in P["moving_lane_gaps"]]
            w = float(P["moving_width"])
        else:
            if not fz:
                raise SystemExit(f"[ERROR] no frozen geometry for {ctx} (run the Stage 2 pilot first)")
            gaps, w = [float(fz["lane_gap_m"])], float(fz["width_m"])
        return [(f"w{w:.2f}_g{gp:.2f}", (lambda s, gp=gp, w=w: moving_env(ctx, G["moving"], w, gp, s, J["moving"])))
                for gp in gaps]
    if phase == "s2pilot":
        widths = [float(x) for x in P["static_widths"]]
    else:
        if not fz:
            raise SystemExit(f"[ERROR] no frozen geometry for {ctx} (run the Stage 2 pilot first)")
        widths = [float(fz["width_m"])]
    return [(f"w{w:.2f}", (lambda s, w=w: static_env(ctx, c, G["static"], w, s, J["static"]))) for w in widths]


# ------------------------------------------------------------- Stage 3 seeds
def family_of(S, seed):
    for name, f in S["stage3"]["families"].items():
        lo, hi = f["seeds"]
        if lo <= seed <= hi or f.get("pilot") == seed:
            return name, f
    raise SystemExit(f"[ERROR] seed {seed} in no Stage 3 family")


def stage3_seed_doc(S, seed, control) -> tuple:
    cross = PROJECT_ROOT / "configs" / "campaigns" / "cross" / f"campaign_h8_a3_cross_s{seed}.yaml"
    if not cross.exists():
        r = subprocess.run([sys.executable, "scripts/make_cross_campaign.py", "--seeds", str(seed)],
                           cwd=PROJECT_ROOT, capture_output=True, text=True)
        if r.returncode != 0 or not cross.exists():
            raise SystemExit(f"[ERROR] make_cross_campaign seed {seed}:\n{r.stdout}{r.stderr}")
    base_cfg = load_config(common_path=str(cross))
    fam, f = family_of(S, seed)
    exch = (base_cfg.get("scenario_meta") or {}).get("exchanges") or []
    r = rng("stage3", seed)
    over, timing = {}, []
    for ex in exch:
        b0, e0 = float(ex["belt_start_at"]), float(ex["edge_start_at"])
        if fam == "NOMINAL":
            b1 = b0
        elif fam == "BOTTLENECK":
            b1 = float(f["exchange_start_s"])
        else:
            lo, hi = f["north_start_s"] if ex["side"] == "north" else f["south_start_s"]
            b1 = round(r.uniform(float(lo), float(hi)), 1)
        e1 = round(b1 + (e0 - b0), 2)
        timing.append({"side": ex["side"], "belt": ex["belt"], "edge": ex["edge"],
                       "belt_start_at": [b0, b1], "edge_start_at": [e0, e1]})
        if fam != "NOMINAL":
            over[ex["belt"]] = {"walk": {"start_at": b1}}
            over[ex["edge"]] = {"walk": {"start_at": e1}}
    doc = {"base": str(cross.relative_to(PROJECT_ROOT)),
           "scenario_meta": {"stage23_900": {"stage": "Stage 3", "seed": seed, "family": fam,
                                             "family_note": f["note"], "exchange_timing": timing}}}
    if over:
        doc["humans"] = over
    doc["recording"] = dict(STAGE3_RECORDING)
    for k, v in control.items():
        if k == "recording":
            doc["recording"] = {**doc["recording"], **v, "version": STAGE3_RECORDING["version"]}
        elif k == "navigation":
            doc[k] = {**doc.get(k, {}), **v}
        else:
            doc[k] = v
    text = TAG + f"# Stage 3 seed {seed}, family {fam}\n" + yaml.safe_dump(doc, sort_keys=False)
    return text, {"seed": seed, "family": fam, "exchange_timing": timing}


# ------------------------------------------------------------------- main
def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=str(CFG))
    ap.add_argument("--phase", required=True, choices=("s2pilot", "s2main", "s3pilot", "s3main", "s3dup"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    cfgp = Path(a.config).resolve()
    S = yaml.safe_load(cfgp.read_text())
    cfg_rel = str(cfgp.relative_to(PROJECT_ROOT))
    base = load_config(common_path=str(PROJECT_ROOT / "configs" / "common.yaml"))
    control = yaml.safe_load((PROJECT_ROOT / S["control_overlay"]).read_text())
    OUT = PROJECT_ROOT / S["out_dir"]
    stage = 2 if a.phase.startswith("s2") else 3

    S2 = {"anchor_m": S["anchor_m"], "anchor_provenance": S["anchor_provenance"],
          "moving_reference_speed_mps": S["moving_reference_speed_mps"],
          "alphas": sorted(set(map(float, S["alphas"])) | set(map(float, S["stage3_alphas"])))}
    sh = shapes(S2, base)
    probs = check_shapes(S2, sh)
    if probs:
        print("[ERROR] shape checks failed:\n  " + "\n  ".join(probs))
        return 1
    allc = conditions(S2, sh)
    b2 = next(k for k in allc if k.startswith("B2"))
    files = {}
    for cn, (label, cs, _al) in allc.items():
        if cn == "B1":
            continue
        files[OUT / "conditions" / f"{cn}.yaml"] = (
            TAG + yaml.safe_dump({"scenario": {"name": f"{S['version']}_{cn}", "label": label}, "comfort_space": cs},
                                 sort_keys=False))
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=PROJECT_ROOT, capture_output=True,
                            text=True).stdout.strip()
    plan = {"version": S["version"], "phase": a.phase, "stage": stage, "config": cfg_rel, "commit_at_plan": commit,
            "control_mode": control["control"]["mode"], "anchor_m": S["anchor_m"],
            "anchor_provenance": S["anchor_provenance"], "moving_reference_speed_mps": S["moving_reference_speed_mps"],
            "templates_raw": sh["raw"], "templates_normalised": sh["normalised"], "min_radius_m": sh["min_radius_m"],
            "min_alpha_without_clip": sh["min_alpha_without_clip"],
            "extents_by_alpha": {atag(x): s2.scaled(sh["normalised"], x) for x in sh["alphas"]},
            "reference": S["reference"], "criteria": S["criteria"], "references": cref.describe(),
            "amr_half_length_m": float(base["amr"]["footprint_length"]) / 2.0,
            "amr_half_width_m": float(base["amr"]["footprint_width"]) / 2.0,
            "human_radius_m": float(base["humans"]["radius"]), "frozen": S.get("frozen"),
            "scenarios": {}, "geometries": {}, "seeds": {}}
    rows = []     # (order key, manifest line)
    envs = {}     # env name -> (path, condition names)
    rel = OUT.relative_to(PROJECT_ROOT)

    if stage == 2:
        alphas = [float(x) for x in (S["stage2"]["pilot"]["alphas"] if a.phase == "s2pilot" else S["alphas"])]
        seeds = (S["stage2"]["pilot"]["seeds"] if a.phase == "s2pilot"
                 else list(range(S["stage2"]["main_seeds"][0], S["stage2"]["main_seeds"][1] + 1)))
        conds = [cname(x) for x in alphas]
        plan["conditions"] = {cn: {"label": allc[cn][0], "alpha": allc[cn][2]} for cn in conds}
        plan["alphas"] = alphas
        for ctx, c in S["stage2"]["contexts"].items():
            ent = {k: c.get(k) for k in ("state", "context", "intended_sector", "primary", "label")}
            ent["status"] = "RUN"
            fz = (S.get("frozen") or {}).get(ctx)
            if a.phase == "s2main" and isinstance(fz, dict) and fz.get("status"):
                ent["identification_at_pilot"] = fz["status"]
            ent["run_conditions"] = conds
            plan["scenarios"][ctx] = ent
            for gid, build in stage2_geometries(S, a.phase, ctx, c):
                for seed in seeds:
                    ov, meta = build(seed)
                    env = f"{ctx}_{gid}_s{seed:03d}"
                    p = OUT / "stage2" / "envs" / f"{env}.yaml"
                    files[p] = stage2_env_text(S, ctx, c, gid, seed, ov, control)
                    plan["geometries"][env] = {"scenario": ctx, "geometry": gid, "seed": seed, **meta,
                                               "start": ov["navigation"]["start"], "goal": ov["navigation"]["goal"],
                                               "person": ov["humans"]["a"]}
                    envs[env] = (p, conds)
                    for cn in conds:
                        tid = f"{env}_{cn}"
                        rows.append(((seed, rng("order", a.phase, seed, tid).random()),
                                     f"{tid}\t{seed}\t{rel}/conditions/{cn}.yaml\t{rel}/stage2/envs/{env}.yaml"))
    else:
        T = S["stage3"]
        pol = [b2 if v == "B2" else cname(v) for v in T["policies"].values()]
        plan["policies"] = dict(zip(T["policies"].keys(), pol))
        plan["conditions"] = {cn: {"label": allc[cn][0], "alpha": allc[cn][2]} for cn in pol}
        plan["encounter"], plan["winner_rule"] = T["encounter"], T["winner_rule"]
        if a.phase == "s3main":
            seeds = list(range(T["main_seeds"][0], T["main_seeds"][1] + 1))
        else:
            seeds = list(T["pilot_seeds"]) if a.phase == "s3pilot" else list(T["duplicate_control"]["seeds"])
        order = list(seeds)
        rng("s3order", a.phase).shuffle(order)
        for k, seed in enumerate(order):
            text, meta = stage3_seed_doc(S, seed, control)
            p = OUT / "stage3" / "seeds" / f"s{seed}.yaml"
            files[p] = text
            plan["seeds"][str(seed)] = meta
            env = f"s{seed}"
            if a.phase == "s3dup":
                cn = b2
                envs[env] = (p, [cn])
                for rep in range(1, int(T["duplicate_control"]["repeats"]) + 1):
                    tid = f"s{seed}_{cn}_dup{rep}"
                    rows.append(((rep, k), f"{tid}\t{seed}\t{rel}/conditions/{cn}.yaml\t{rel}/stage3/seeds/s{seed}.yaml"))
                continue
            envs[env] = (p, pol)
            rot = pol[k % len(pol):] + pol[:k % len(pol)]        # Latin-square rotation per seed
            for j, cn in enumerate(rot):
                tid = f"s{seed}_{cn}"
                rows.append(((k, j), f"{tid}\t{seed}\t{rel}/conditions/{cn}.yaml\t{rel}/stage3/seeds/s{seed}.yaml"))

    root = OUT / ".check" if a.check else OUT
    for p, text in files.items():
        q = root / p.relative_to(OUT)
        q.parent.mkdir(parents=True, exist_ok=True)
        if not a.check and q.exists() and q.read_text() != text:
            print(f"[ERROR] {q.relative_to(PROJECT_ROOT)} exists with different content (immutable); bump version")
            return 1
        q.write_text(text, encoding="utf-8")

    from comfort_core.layout import validate
    errors = []
    for env, (p, conds) in envs.items():
        q = root / p.relative_to(OUT)
        sigs = {}
        for cn in conds:
            cfg = load_config(scenario=str(root / "conditions" / f"{cn}.yaml"), common_path=str(q))
            sigs[cn] = s2.physical_signature(cfg)
            errors += [f"{env} {cn}: {x}" for x in cm.config_problems(cfg)]
        if len(set(sigs.values())) != 1:
            errors.append(f"{env}: physical configs differ between conditions {sigs}")
        sig = next(iter(sigs.values()))
        merged = load_config(common_path=str(q))
        if stage == 2:
            g = plan["geometries"][env]
            g["physical_signature"] = sig
            pv = validate(merged)
            if pv:
                errors.append(f"{env}: layout {pv}")
            if plan["scenarios"][g["scenario"]]["state"] == "moving":
                pr = g["person"]
                if abs(g["human_lane_y"] - g["amr_lane_y"]) < 1e-6:
                    errors.append(f"{env}: walker and AMR share a lane")
                if not (pr["route"][0][0] - pr["position"][0]) * (g["goal"][0] - g["start"][0]) < 0:
                    errors.append(f"{env}: not opposite directions")
        else:
            m = plan["seeds"][env[1:]]
            m["physical_signature"] = sig
            for t in m["exchange_timing"]:
                for role, key in ((t["belt"], "belt_start_at"), (t["edge"], "edge_start_at")):
                    got = float(((merged["humans"].get(role) or {}).get("walk") or {}).get("start_at", -1))
                    if abs(got - t[key][1]) > 1e-6:
                        errors.append(f"{env}: {role} walk start {got} != planned {t[key][1]}")
                    if not ((merged["humans"][role].get("walk") or {}).get("route")):
                        errors.append(f"{env}: {role} lost its route")
    if a.check:
        shutil.rmtree(root)
    if errors:
        print("[ERROR]\n  " + "\n  ".join(errors[:40]))
        return 1
    rows.sort(key=lambda x: x[0])
    lines = [ln for _k, ln in rows]
    batch = PROJECT_ROOT / f"{S['batch_prefix']}_{a.phase}"
    text = (f"# {S['version']} {a.phase}\n# trial_id\trepeat\tcondition\tconfig\n" + "\n".join(lines) + "\n")
    plan["n_trials"] = len(lines)
    plan["checksums"] = {"manifest_sha256_16": sha(text), "config_sha256_16": sha(cfgp.read_text()),
                         "files": {str(p.relative_to(PROJECT_ROOT)): sha(t) for p, t in sorted(files.items())}}
    print(f"{S['version']} {a.phase}: {len(lines)} trials, {len(envs)} envs/seeds, alphas "
          f"{plan.get('alphas', plan.get('policies'))} -> {batch.relative_to(PROJECT_ROOT)}")
    if a.check:
        print("check OK (nothing written)")
        return 0
    batch.mkdir(parents=True, exist_ok=True)
    mf = batch / "manifest.tsv"
    if mf.exists() and mf.read_text() != text and any((batch / "trials").glob("*/DONE")):
        print("[ERROR] batch has finished trials and a different manifest; not overwriting")
        return 1
    mf.write_text(text)
    (batch / "plan.json").write_text(json.dumps(plan, indent=1))
    print("written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
