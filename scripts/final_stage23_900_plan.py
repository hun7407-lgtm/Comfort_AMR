#!/usr/bin/env python3
"""FINAL Stage 2 (750) + Stage 3 (150) Nav2-only: configs, manifests, plan.json.

    python3 scripts/final_stage23_900_plan.py --phase s2pilot   # policy-neutral geometry pilot
    python3 scripts/final_stage23_900_plan.py --phase s2main    # 5 contexts x 5 alpha x 30 seeds = 750
    python3 scripts/final_stage23_900_plan.py --phase s3pilot   # 3 pilot seeds (one per family) x 5 policies
    python3 scripts/final_stage23_900_plan.py --phase s3main    # 30 holdout seeds x 5 policies = 150
    python3 scripts/final_stage23_900_plan.py --phase s3dup     # duplicate-control diagnostic (outside 150)
    add --check to verify without writing.

Source of every number: configs/final_nav2only_stage23_900/stage23_900.yaml.
Writes only under its out_dir and the new batch folders <batch_prefix>_<phase>; a
generated file that already exists with different content is an error (immutable).
Refuses when: a shape is not a pure multiple of the normalised template or would be
clipped at min_radius; conditions of one env / seed differ in anything but the Comfort
Space policy (physical signature incl. control mode, buffer, safety); the merged config
breaks nav2_only (comfort_core/control_mode.py); layout validation fails; MV-P lanes are
not opposite; a Stage 3 family override did not land in the merged config.
Protocol: docs/FINAL_STAGE2_STAGE3_NAV2_ONLY_PROTOCOL_20261127.md
"""

