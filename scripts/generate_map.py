#!/usr/bin/env python3
"""Generate the Nav2 occupancy grid from the corridor config.

Runs in any Python. No ROS, no Isaac Sim, no image library.

Why generate instead of running SLAM
------------------------------------
The corridor's exact dimensions are already in configs/common.yaml, so
mapping it with a laser would only add noise to something we know
precisely. Generating it also guarantees that B2 and B3 navigate on a
byte-identical map, which a SLAM run could not promise.

What goes in the map
--------------------
Static building structure only: the walls and the workstations. The
humans are deliberately left out. They reach Nav2 through the costmap's
obstacle layer instead, which is the same channel the Comfort Space will
use, so the difference between B2 and B3 stays in one place.

    ./scripts/generate_map.py
    ./scripts/generate_map.py --config configs/demo_weave.yaml
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from comfort_core import load_config, resolve_path
from comfort_core.layout import corridor_bounds, placed_entries

# ROS map_server conventions with negate=0.
FREE = 254
OCCUPIED = 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="configs/common.yaml")
    parser.add_argument("--resolution", type=float, default=0.05,
                        help="metres per pixel (default 0.05)")
    parser.add_argument("--out-dir", default="configs/nav2",
                        help="where to write corridor_map.pgm and .yaml")
    args = parser.parse_args()

    cfg = load_config(common_path=args.config)
    bounds = corridor_bounds(cfg)
    res = float(args.resolution)
    thickness = float(cfg["corridor"]["wall_thickness"])

    # One wall thickness of solid material on every side, plus a small
    # border so the costmap inflation has somewhere to live.
    border = thickness + 0.20
    x_min, x_max = bounds.x_min - border, bounds.x_max + border
    y_min, y_max = bounds.y_min - border, bounds.y_max + border

    width = int(math.ceil((x_max - x_min) / res))
    height = int(math.ceil((y_max - y_min) / res))

    # Start fully occupied, then carve out the corridor interior. Doing
    # it this way means the walls have real thickness and the outside of
    # the building is solid, so a planner can never route around it.
    grid = bytearray([OCCUPIED]) * (width * height)

    def world_to_px(wx: float, wy: float):
        col = int((wx - x_min) / res)
        # Image row 0 is the top of the map, which is maximum y.
        row = int((y_max - wy) / res)
        return col, row

    def fill_rect(x0, y0, x1, y1, value):
        c0, r1 = world_to_px(x0, y0)
        c1, r0 = world_to_px(x1, y1)
        for row in range(max(r0, 0), min(r1, height)):
            base = row * width
            for col in range(max(c0, 0), min(c1, width)):
                grid[base + col] = value

    fill_rect(bounds.x_min, bounds.y_min, bounds.x_max, bounds.y_max, FREE)

    stations = cfg["stations"]
    sx, sy, _ = (float(v) for v in stations["size"])
    for key in placed_entries(stations):
        cx, cy = (float(v) for v in stations[key]["position"])
        fill_rect(cx - sx / 2.0, cy - sy / 2.0,
                  cx + sx / 2.0, cy + sy / 2.0, OCCUPIED)

    out_dir = resolve_path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    pgm_path = out_dir / "corridor_map.pgm"
    yaml_path = out_dir / "corridor_map.yaml"

    with open(pgm_path, "wb") as f:
        f.write(b"P5\n")
        f.write(b"# generated by scripts/generate_map.py from "
                + str(args.config).encode() + b"\n")
        f.write(f"{width} {height}\n255\n".encode())
        f.write(bytes(grid))

    # origin is the world position of the image's bottom-left pixel.
    yaml_path.write_text(
        "# Generated by scripts/generate_map.py. Do not edit by hand:\n"
        f"# regenerate it after changing the corridor in {args.config}.\n"
        f"image: {pgm_path.name}\n"
        f"resolution: {res}\n"
        f"origin: [{x_min:.4f}, {y_min:.4f}, 0.0]\n"
        "negate: 0\n"
        "occupied_thresh: 0.65\n"
        "free_thresh: 0.196\n"
    )

    free_px = sum(1 for v in grid if v == FREE)
    print(f"wrote {pgm_path}")
    print(f"      {width} x {height} px at {res} m/px")
    print(f"      origin ({x_min:.2f}, {y_min:.2f}), "
          f"covers x[{x_min:.2f}, {x_max:.2f}] y[{y_min:.2f}, {y_max:.2f}]")
    print(f"      {free_px} free px = {free_px * res * res:.2f} m2")
    print(f"wrote {yaml_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
