#!/usr/bin/env python3
"""Generate the Nav2 occupancy grid from the scene config.

Runs in any Python. No ROS, no Isaac Sim, no image library.

Why generate instead of running SLAM
------------------------------------
The corridor's exact dimensions are already in configs/common.yaml, so
mapping it with a laser would only add noise to something we know
precisely. Generating it also guarantees that B2 and B3 navigate on a
byte-identical map, which a SLAM run could not promise.

What goes in the map
--------------------
Static building structure only: the walls and the workstations. The
humans are deliberately left out. They reach Nav2 through the costmap's
obstacle layer instead, which is the same channel the Comfort Space will
use, so the difference between B2 and B3 stays in one place.

    ./scripts/generate_map.py
    ./scripts/generate_map.py --config configs/demo_weave.yaml
    ./scripts/generate_map.py --config configs/factory.yaml

A config with a `factory` section maps the bay instead of the corridor:
the shell, the columns and the machines, written to factory_map.*. The
people are left out of that one too, for the same reason.
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from comfort_core import load_config, resolve_path
from comfort_core.factory_layout import build_layout, navigable_rects
from comfort_core.layout import corridor_bounds, placed_entries

# ROS map_server conventions with negate=0.
FREE = 254
OCCUPIED = 0


class Grid:
    """An occupancy grid in world coordinates, solid until carved out.

    Starting solid rather than empty means the outside of the building
    is occupied, so a planner can never route around the walls -- and a
    rectangle that is forgotten shows up as a wall rather than as open
    floor you can drive through.
    """

    def __init__(self, x_min: float, y_min: float, x_max: float,
                 y_max: float, res: float) -> None:
        self.x_min, self.y_min, self.res = x_min, y_min, res
        self.y_max = y_max
        self.width = int(math.ceil((x_max - x_min) / res))
        self.height = int(math.ceil((y_max - y_min) / res))
        self.cells = bytearray([OCCUPIED]) * (self.width * self.height)

    def _px(self, wx: float, wy: float):
        # Image row 0 is the top of the map, which is maximum y.
        return int((wx - self.x_min) / self.res), int((self.y_max - wy) / self.res)

    def fill(self, x0: float, y0: float, x1: float, y1: float,
             value: int) -> None:
        c0, r1 = self._px(x0, y0)
        c1, r0 = self._px(x1, y1)
        for row in range(max(r0, 0), min(r1, self.height)):
            base = row * self.width
            for col in range(max(c0, 0), min(c1, self.width)):
                self.cells[base + col] = value

    def write(self, pgm_path: Path, yaml_path: Path, source: str,
              res: float) -> None:
        with open(pgm_path, "wb") as f:
            f.write(b"P5\n")
            f.write(b"# generated by scripts/generate_map.py from "
                    + source.encode() + b"\n")
            f.write(f"{self.width} {self.height}\n255\n".encode())
            f.write(bytes(self.cells))

        # origin is the world position of the image's bottom-left pixel.
        yaml_path.write_text(
            "# Generated by scripts/generate_map.py. Do not edit by hand:\n"
            f"# regenerate it after changing the scene in {source}.\n"
            f"image: {pgm_path.name}\n"
            f"resolution: {res}\n"
            f"origin: [{self.x_min:.4f}, {self.y_min:.4f}, 0.0]\n"
            "negate: 0\n"
            "occupied_thresh: 0.65\n"
            "free_thresh: 0.196\n"
        )

    def report(self, pgm_path: Path, yaml_path: Path, res: float) -> None:
        free_px = sum(1 for v in self.cells if v == FREE)
        x_max = self.x_min + self.width * res
        y_min = self.y_max - self.height * res
        print(f"wrote {pgm_path}")
        print(f"      {self.width} x {self.height} px at {res} m/px")
        print(f"      origin ({self.x_min:.2f}, {y_min:.2f}), "
              f"covers x[{self.x_min:.2f}, {x_max:.2f}] "
              f"y[{y_min:.2f}, {self.y_max:.2f}]")
        print(f"      {free_px} free px = {free_px * res * res:.2f} m2")
        print(f"wrote {yaml_path}")


def _free_beside(slot, layout, side: int) -> bool:
    """Is the slot immediately left (-1) or right (+1) of this one free?"""
    edge = slot.x_min if side < 0 else slot.x_max
    for other in layout.cart_slots_free:
        if other is slot:
            continue
        if abs(other.y_min - slot.y_min) > 1e-6:
            continue
        touching = (abs(other.x_max - edge) < 1e-6 if side < 0
                    else abs(other.x_min - edge) < 1e-6)
        if touching:
            return True
    return False


def factory_map(cfg, args) -> int:
    """The bay: free floor, with the shell, columns and machines solid.

    The machines are in the map because they do not move; the people
    are not, because they do. That is the same split the corridor map
    makes between its walls and its humans.
    """
    layout = build_layout(cfg)
    f = cfg["factory"]
    res = float(args.resolution)
    border = float(f["wall_thickness"]) + 0.20

    grid = Grid(layout.x_min - border, layout.y_min - border,
                layout.x_max + border, layout.y_max + border, res)

    if f.get("map", {}).get("lanes_only", False):
        # Only the marked floor is driveable: aisles, crossings, the
        # pull-off refuges and the cart blocks. Everything else stays
        # solid. Note `navigable_rects`, not `drivable_rects`: the
        # robot may be sent into a cart block, it just may not hide in
        # one.
        #
        # The default below leaves the work zones open, on the grounds
        # that they are floor and the robot could physically cross
        # them. In a bay whose zones are packed with machines that
        # makes no difference. In one with a long run of racking and a
        # metre of clear floor in front of it, it makes all the
        # difference: the planner finds that strip, drives the length
        # of the building through the storage area, and passes nobody
        # -- measured in the U bay, a 19.6 m route at y = 6.4 to 7.1,
        # straight over the parked carts. A robot that avoids every
        # person by leaving the aisle is not a test of how it behaves
        # around people.
        # A little wider than the paint. There is no wall at the edge
        # of a painted lane, and treating one as a wall strands the
        # robot the first time it steps over the line to let somebody
        # past: measured, it sidestepped 0.26 m out of a 1.5 m aisle
        # and the planner then could not plan from where it stood.
        #
        # The margin has to be small. What it must not do is reconnect
        # the clear strip in front of the racking, a metre or more
        # outside the lane, which is the route this whole option
        # exists to close off.
        margin = float(f.get("map", {}).get("lane_margin", 0.30))
        free_slots = {r.name for r in layout.cart_slots_free}
        # An empty cart slot opens almost to its full width, but NOT
        # into its neighbour: a divider is left solid on each side.
        #
        # Both halves of that matter, and each was learnt the hard way.
        #
        # The divider is what stops a block's frontage becoming a second
        # corridor beside the aisle. With two or three empty slots in a
        # row fully open, the planner ran the length of the block
        # through them, clipped the inflation of a parked cart and the
        # protective field stopped the robot for good (B3, at
        # (5.47, 5.70)).
        #
        # The width is what stops the slot being a trap. A 0.80 m mouth
        # was tried: the inflation radius is 0.34 m, so 0.68 m of that
        # 0.80 m was inflated from both sides at once, there was no
        # low-cost channel down the middle for the controller to hold,
        # and the robot drifted until it had a parked cart 0.04 m off
        # its flank -- then the protective stop held it there until the
        # trial gave up (B1, at (5.27, 5.47)). At 1.30 m there is
        # 0.52 m of clear channel, and a robot that keeps the
        # inflation radius off the carts cannot be close enough to one
        # to trip its own protective field.
        #
        # 0.20 m, which is four cells at this resolution: the divider
        # has to survive the grid rounding outward at both ends, and a
        # one-cell line that half of it rounds away is not a divider.
        divider = float(f.get("map", {}).get("slot_divider", 0.20))
        for rect in navigable_rects(layout):
            if rect.name in free_slots:
                # Empty slots next to each other open as ONE space.
                #
                # The divider only goes where a free slot meets
                # something that is not free: a parked cart, or the end
                # of the block. Between two empty slots there is
                # nothing to divide, and walling them apart left the
                # robot a 1.40 x 1.05 m pocket to maneouvre in, which
                # is not enough for a 0.70 x 0.48 m vehicle that has to
                # keep a 0.45 m protective field clear -- it drove in,
                # tripped its own field on the cart behind, and could
                # not get out again.
                #
                # Merged, the same block offers a 2.80 m frontage, and
                # the one thing the divider is there for -- stopping
                # the whole frontage becoming a second corridor beside
                # the aisle -- is still done by the carts themselves.
                left = rect.x_min + (0.0 if _free_beside(rect, layout, -1)
                                     else divider / 2.0)
                right = rect.x_max - (0.0 if _free_beside(rect, layout, +1)
                                      else divider / 2.0)
                grid.fill(left, rect.y_min - margin, right, rect.y_max, FREE)
            else:
                grid.fill(rect.x_min - margin, rect.y_min - margin,
                          rect.x_max + margin, rect.y_max + margin, FREE)
        # Then put the parked carts back. A cart stands in its slot for
        # the whole trial, so it belongs in the static map exactly as a
        # machine does: the planner should route round it rather than
        # drive at it and leave the local costmap to notice. Opening
        # the block and then leaving the carts out of it was what let a
        # route be planned straight through a block of 22 of them.
        for slot in layout.cart_slots_taken:
            grid.fill(slot.x_min, slot.y_min, slot.x_max, slot.y_max,
                      OCCUPIED)
    else:
        grid.fill(layout.x_min, layout.y_min, layout.x_max, layout.y_max, FREE)

        half = float(f["column_size"]) / 2.0
        for cx, cy in layout.columns:
            grid.fill(cx - half, cy - half, cx + half, cy + half, OCCUPIED)
        for station in layout.stations:
            box = station.footprint
            grid.fill(box.x_min, box.y_min, box.x_max, box.y_max, OCCUPIED)

    out_dir = resolve_path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    pgm_path = out_dir / "factory_map.pgm"
    yaml_path = out_dir / "factory_map.yaml"
    grid.write(pgm_path, yaml_path, str(args.config), res)
    grid.report(pgm_path, yaml_path, res)
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="configs/common.yaml")
    parser.add_argument("--resolution", type=float, default=0.05,
                        help="metres per pixel (default 0.05)")
    parser.add_argument("--out-dir", default="configs/nav2",
                        help="where to write corridor_map.pgm and .yaml")
    args = parser.parse_args()

    cfg = load_config(common_path=args.config)

    named = cfg.get("nav2", {}).get("map")
    if named:
        # The 3D configs navigate on a map SLAM built, which is not this
        # script's to write. Generating one anyway would leave two maps
        # of the same bay side by side, and the next person to look would
        # have no way to tell which one the run used.
        print(f"this config navigates on {named}, which is built by "
              f"./scripts/run_mapping.sh.")
        print("nothing to generate.")
        return 0

    if "factory" in cfg:
        return factory_map(cfg, args)

    bounds = corridor_bounds(cfg)
    res = float(args.resolution)
    thickness = float(cfg["corridor"]["wall_thickness"])

    # One wall thickness of solid material on every side, plus a small
    # border so the costmap inflation has somewhere to live.
    border = thickness + 0.20
    x_min, x_max = bounds.x_min - border, bounds.x_max + border
    y_min, y_max = bounds.y_min - border, bounds.y_max + border

    width = int(math.ceil((x_max - x_min) / res))
    height = int(math.ceil((y_max - y_min) / res))

    # Start fully occupied, then carve out the corridor interior. Doing
    # it this way means the walls have real thickness and the outside of
    # the building is solid, so a planner can never route around it.
    grid = bytearray([OCCUPIED]) * (width * height)

    def world_to_px(wx: float, wy: float):
        col = int((wx - x_min) / res)
        # Image row 0 is the top of the map, which is maximum y.
        row = int((y_max - wy) / res)
        return col, row

    def fill_rect(x0, y0, x1, y1, value):
        c0, r1 = world_to_px(x0, y0)
        c1, r0 = world_to_px(x1, y1)
        for row in range(max(r0, 0), min(r1, height)):
            base = row * width
            for col in range(max(c0, 0), min(c1, width)):
                grid[base + col] = value

    fill_rect(bounds.x_min, bounds.y_min, bounds.x_max, bounds.y_max, FREE)

    stations = cfg["stations"]
    sx, sy, _ = (float(v) for v in stations["size"])
    for key in placed_entries(stations):
        cx, cy = (float(v) for v in stations[key]["position"])
        fill_rect(cx - sx / 2.0, cy - sy / 2.0,
                  cx + sx / 2.0, cy + sy / 2.0, OCCUPIED)

    out_dir = resolve_path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    pgm_path = out_dir / "corridor_map.pgm"
    yaml_path = out_dir / "corridor_map.yaml"

    with open(pgm_path, "wb") as f:
        f.write(b"P5\n")
        f.write(b"# generated by scripts/generate_map.py from "
                + str(args.config).encode() + b"\n")
        f.write(f"{width} {height}\n255\n".encode())
        f.write(bytes(grid))

    # origin is the world position of the image's bottom-left pixel.
    yaml_path.write_text(
        "# Generated by scripts/generate_map.py. Do not edit by hand:\n"
        f"# regenerate it after changing the corridor in {args.config}.\n"
        f"image: {pgm_path.name}\n"
        f"resolution: {res}\n"
        f"origin: [{x_min:.4f}, {y_min:.4f}, 0.0]\n"
        "negate: 0\n"
        "occupied_thresh: 0.65\n"
        "free_thresh: 0.196\n"
    )

    free_px = sum(1 for v in grid if v == FREE)
    print(f"wrote {pgm_path}")
    print(f"      {width} x {height} px at {res} m/px")
    print(f"      origin ({x_min:.2f}, {y_min:.2f}), "
          f"covers x[{x_min:.2f}, {x_max:.2f}] y[{y_min:.2f}, {y_max:.2f}]")
    print(f"      {free_px} free px = {free_px * res * res:.2f} m2")
    print(f"wrote {yaml_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
