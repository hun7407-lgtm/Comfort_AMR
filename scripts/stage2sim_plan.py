#!/usr/bin/env python3
"""Stage 2 (simulation): write environments, conditions and the manifest.

    python3 scripts/stage2sim_plan.py              # write everything
    python3 scripts/stage2sim_plan.py --check      # print the plan, write nothing
    python3 scripts/stage2sim_plan.py --smoke      # 1 repeat: B1, static 0.90, static + adaptive 0.54

Plain Python 3. Reads configs/stage2sim/stage2sim.yaml. Writes
    configs/stage2sim/envs/<scenario>.yaml          corridor + one person
    configs/stage2sim/conditions/<cond>.yaml        B1 / static r / adaptive r
    <batch>/manifest.tsv                            trial_id, repeat, condition, config
    <batch>/plan.json                               ladder, shapes, feasibility, references
Run with scripts/final_run.py --dir <batch> (resumable, same runner as the
final Stage 1/3). Existing batches and configs are never touched.

Versions
--------
static     circle of radius r.
adaptive   the literature iso-comfort shape (comfort_reference.required_extents
           at the primary target) scaled so the TESTED direction equals r;
           the other directions keep their ratio to it. So both versions
           shrink by the same ladder in the direction that is tested.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

import yaml  # noqa: E402

from comfort_core import comfort_reference as cref  # noqa: E402
from comfort_core.config import load_config  # noqa: E402
from comfort_core.contexts import facing_deg  # noqa: E402

CFG = PROJECT_ROOT / "configs" / "stage2sim" / "stage2sim.yaml"
OUT = PROJECT_ROOT / "configs" / "stage2sim"
HEADER = ("# GENERATED by scripts/stage2sim_plan.py from configs/stage2sim/stage2sim.yaml\n"
          "# -- regenerate, do not hand-edit. Stage 2 (simulation), rev. 2026-11-26.\n")


def tight_width(g: dict, r: float) -> float:
    """Corridor in which the free lane beside the Comfort Space is exactly
    lane_free_m: wall gap + r + lane_free_m + the person's own offset
    (none: r is measured from the person centre)."""
    return round(g["person_wall_gap_m"] + r + g["tight"]["lane_free_m"], 3)


def ladder(spec) -> list:
    s, lo = float(spec["start_m"]), float(spec["min_m"])
    out, k = [], 0
    while True:
        r = s * (1.0 - spec["fraction"] * k) if spec["mode"] == "linear_fraction" else s * spec["ratio"] ** k
        r = round(r, 3)
        if r < lo - 1e-9:
            break
        out.append(r)
        k += 1
    fl = spec.get("floor_m")
    if fl is not None and out and out[-1] > fl + 1e-9:
        out.append(round(float(fl), 3))
    return out


def env_overlay(name: str, sc: dict, g: dict, width=None) -> dict:
    """width None = the fixed 'wide' corridor; else the 'tight' corridor
    of that width (person / walker lane person_wall_gap_m from the +y wall)."""
    if sc["state"] == "moving":
        m = g["moving"]
        w, L = (width or m["corridor_width_m"]), m["corridor_length_m"]
        y = m["lane_y"] if width is None else round(w / 2.0 - g["person_wall_gap_m"], 4)
        # person a walks (a has a character model in common.yaml; c has none)
        humans = {"a": {"position": [m["walker_start_x"], y], "state": "moving",
                        "route": [[m["walker_end_x"], y]], "avoid_robot": False},
                  "b": {"enabled": False}, "c": {"enabled": False}}
        nav = {"start": [m["start_x"], y], "goal": [m["goal_x"], y]}
    else:
        w, L = (width or g["corridor_width_m"]), g["corridor_length_m"]
        py = round(w / 2.0 - g["person_wall_gap_m"], 4)
        ly = round(py - g["path_offset_m"], 4)
        # person on the +y wall, passage toward -y: bearing person -> passage -90 deg
        f = facing_deg(sc["context"], -90.0)
        f = ((f + 180.0) % 360.0) - 180.0
        humans = {"a": {"position": [0.0, py], "state": sc["state"], "facing_deg": f},
                  "b": {"enabled": False}, "c": {"enabled": False}}
        nav = {"start": [g["start_x"], ly], "goal": [g["goal_x"], ly]}
    return {
        "base": "configs/common.yaml",
        "scenario_meta": {"scenario_id": f"stage2sim_{name}", "stage": "Stage 2 (simulation)",
                          "label": sc["label"], "human_count": 1, "amr_count": 1,
                          "aisle_width_m": w},
        "corridor": {"width": w, "length": L, "center": [0.0, 0.0]},
        "stations": {"a": {"enabled": False}, "b": {"enabled": False}},
        "humans": humans,
        "navigation": nav,
        "fleet": {"enabled": False},
    }


def adaptive_block(shape: dict, tested: str, r: float) -> dict:
    """state_directional extents for a stationary / engaged person: the
    literature shape scaled so `tested` == r. Moving people get a circle r
    (not present in these scenarios)."""
    k = r / shape[tested]
    ext = {d: round(shape[d] * k, 3) for d in ("front", "side", "rear")}
    one = {"front_m": ext["front"], "side_m": ext["side"], "rear_m": ext["rear"], "heading_source": "body"}
    mv = {"heading_source": "velocity", "heading_min_speed_mps": 0.1,
          "speed_mapping": {d: {"intercept_m": r, "gain_s": 0.0, "min_m": r, "max_m": r}
                            for d in ("front", "side", "rear")}}
    return {"policy": "state_directional",
            "directional": {"station_engaged": dict(one), "stationary": dict(one), "moving": mv},
            "aisle_scaling": {"enabled": False}}, ext


def condition(name: str, label: str, cs: dict) -> str:
    return HEADER + yaml.safe_dump({"scenario": {"name": name, "label": label}, "comfort_space": cs},
                                   sort_keys=False)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--smoke", action="store_true", help="write <batch>_smoke with 1 repeat of 0.90 and 0.54")
    args = ap.parse_args()
    S = yaml.safe_load(CFG.read_text())
    lad = ladder(S["ladder"])
    crit, refc = S["criteria"], S["reference"]
    base = load_config(common_path=str(PROJECT_ROOT / "configs" / "common.yaml"))
    hw = float(base["amr"]["footprint_width"]) / 2.0
    state_ref = {k: refc[k] for k in ("stationary", "station_engaged", "moving")}

    plan = {"ladder_m": lad, "variants": S["variants"], "amr_half_width_m": hw,
            "reference": refc, "criteria": crit, "scenarios": {}, "references": cref.describe()}
    files, manifest = {}, []
    if S.get("include_b1", True):
        files[OUT / "conditions" / "B1.yaml"] = condition("S2_B1", "B1 no Comfort Space", {"policy": "none"})
    for name, sc in S["scenarios"].items():
        entry = {"label": sc["label"], "state": sc["state"], "tested": sc["tested"],
                 "versions": sc["versions"], "status": "RUN"}
        if sc.get("feasibility_check") == "overtake":
            ov = S["overtake"]
            dv = ov["amr_max_speed_mps"] - ov["walker_speed_mps"]
            need = ov["amr_max_speed_mps"] * ov["gain_m"] / dv if dv > 0 else None
            ok = need is not None and need <= S["geometry"]["moving"]["corridor_length_m"]
            entry["feasibility"] = {
                "amr_max_speed_mps": ov["amr_max_speed_mps"], "walker_speed_mps": ov["walker_speed_mps"],
                "amr_can_overtake": ok, "distance_needed_m": need,
                "reference_curve": None,
                "note": ("Overtaking needs the AMR faster than the walker; the walker's animation speed "
                         "cannot be lowered in this simulation (humans.walk_speed off). No published "
                         "overtaking comfort curve with numeric parameters either (Neggers 2022 Front. "
                         "Exp. 2 gives them only in Fig. 10/11).")}
            if not ok:
                entry["status"] = "INFEASIBLE"
                plan["scenarios"][name] = entry
                continue
        shape = cref.required_extents(crit["primary_target"], sc["state"], hw, state_ref,
                                      refc["distance_basis"], refc["engaged_extra_m"])
        entry["literature_shape_at_primary"] = shape
        entry["required_extent_by_target"] = {
            str(t): cref.required_extents(t, sc["state"], hw, state_ref, refc["distance_basis"],
                                          refc["engaged_extra_m"]) for t in crit["targets"]}
        conds = []      # (condition, radius, version)
        if S.get("include_b1", True):
            conds.append(("B1", None, "B1"))
        for v in sc["versions"]:
            for r in lad:
                if v == "static":
                    cn = f"S2_static_r{r:.3f}"
                    files[OUT / "conditions" / f"{cn}.yaml"] = condition(
                        cn, f"Stage 2 static circle r {r:.3f} m", {"policy": "static", "static_radius": r})
                    conds.append((cn, r, "static"))
                else:
                    if any(shape[d] is None for d in ("front", "side", "rear")):
                        entry.setdefault("notes", []).append(
                            f"adaptive skipped: reference never reaches {crit['primary_target']} in some direction")
                        break
                    cs, ext = adaptive_block(shape, sc["tested"], r)
                    cn = f"S2_{name}_adapt_r{r:.3f}"
                    files[OUT / "conditions" / f"{cn}.yaml"] = condition(
                        cn, f"Stage 2 adaptive ({name}, {sc['tested']} = {r:.3f} m; "
                            f"front {ext['front']} side {ext['side']} rear {ext['rear']})", cs)
                    conds.append((cn, r, "adaptive"))
                    entry.setdefault("adaptive_extents", {})[f"{r:.3f}"] = ext
        entry["conditions"] = []
        g = S["geometry"]
        for var, vspec in S["variants"].items():
            reps = 1 if args.smoke else int(vspec["repeats"])
            for c, r, v in conds:
                if var == "wide":
                    env_name = name
                    width = None
                else:   # tight: corridor per size; B1 in the corridor of the largest size
                    width = tight_width(g, r if r is not None else lad[0])
                    env_name = f"{name}_tight_w{width:.3f}"
                env = OUT / "envs" / f"{env_name}.yaml"
                if env not in files:
                    files[env] = (HEADER + f"# {sc['label']} -- {var} corridor\n"
                                  + yaml.safe_dump(env_overlay(name, sc, g, width), sort_keys=False))
                entry["conditions"].append({"condition": c, "radius_m": r, "version": v, "variant": var,
                                            "env": env_name})
                if args.smoke and not (var in S.get("smoke_variants", ["tight"])
                                       and (v == "B1" or (r is not None and abs(r - 0.54) < 1e-6)
                                            or (v == "static" and abs(r - 0.90) < 1e-6))):
                    continue
                for rep in range(1, reps + 1):
                    tag = c.replace("S2_", "").replace(name + "_", "")
                    tid = f"{name}_{var}_{tag}_rep{rep:02d}"
                    manifest.append((rep, f"{tid}\t{rep}\tconfigs/stage2sim/conditions/{c}.yaml\t"
                                          f"configs/stage2sim/envs/{env_name}.yaml"))
        plan["scenarios"][name] = entry
    # repeat-major order: every condition once before any is repeated
    manifest = [line for _rep, line in sorted(manifest, key=lambda x: x[0])]
    batch = PROJECT_ROOT / (S["batch"] + ("_smoke" if args.smoke else ""))
    print(f"ladder {lad}; {len(manifest)} trials -> {batch.relative_to(PROJECT_ROOT)}")
    for n, e in plan["scenarios"].items():
        print(f"  {n:12s} {e['status']:10s} {e.get('literature_shape_at_primary')}")
    if args.check:
        return 0
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    for p in sorted(x for x in files if x.parent.name == "envs"):
        cfg = load_config(common_path=str(p))
        from comfort_core.layout import validate
        probs = validate(cfg)
        if probs:
            print(f"[ERROR] {p.name}: {probs}")
            return 1
    batch.mkdir(parents=True, exist_ok=True)
    if (batch / "manifest.tsv").exists() and any((batch / "trials").glob("*/DONE")):
        old = (batch / "manifest.tsv").read_text()
        new = "# Stage 2 (simulation)\n# trial_id\trepeat\tcondition\tconfig\n" + "\n".join(manifest) + "\n"
        if old != new:
            print("[ERROR] batch already has finished trials and a different manifest; not overwriting")
            return 1
    (batch / "manifest.tsv").write_text("# Stage 2 (simulation)\n# trial_id\trepeat\tcondition\tconfig\n"
                                        + "\n".join(manifest) + "\n")
    (batch / "plan.json").write_text(json.dumps(plan, indent=1))
    print("written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
