#!/usr/bin/env python3
"""Plan the paper/presentation captures (visual documentation, NOT measurement).

    python3 scripts/paper_capture_plan.py --final-variant buf10
    python3 scripts/paper_capture_plan.py --final-variant buf10 --check

Writes, under --root (default results/captures/paper_261114):

    jobs/still_*.json        isaac_sim/scripts/paper_shots.py jobs (static scenes)
    runs.txt                 recorded capture runs: <scenario overlay> <capture config> <tag>
and capture configs under configs/captures/paper_261114/ (base = an existing
Stage 1 environment or cross campaign config; ONLY the recording camera and
recording.version differ, so the scene is the measured one).

Every scene and condition is an existing, committed one:
    Stage 1 envs       configs/stage1a/envs/*.yaml
    Stage 1 conditions configs/stage1a/conditions{,_nobuf,_<final>}/*.yaml
    cross              configs/campaigns/cross/*.yaml + configs/stage1a/diagnostic/*_cross.yaml
                       (buffer 0 diagnostic, seeds 2/3: B2 comfort_gate_hold, B3-O SUCCESS in
                       results/batches/261114_diag_nobuffer_cross)
    illustrative B3-O  configs/stage3/b3o_initial.yaml, configs/stage3/static_baseline.yaml
Capture runs are re-runs for pictures; their own outcome is recorded and
checked against the original result, never used as a result.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))
sys.path.insert(0, str(PROJECT_ROOT / "scripts"))

import yaml  # noqa: E402

from comfort_core import feasibility as fz  # noqa: E402
from comfort_core.config import load_config  # noqa: E402
from comfort_core.size_sweep import condition_name, write_condition  # noqa: E402
from stage1a_plan import VARIANTS  # noqa: E402

ENV = "configs/stage1a/envs/w{w:.2f}_y0.35_{c}.yaml"
VERSION = "paper_261114"

# Corridor cameras, identical for every width / context / buffer they compare.
TOP = {"name": "top", "ortho": True, "centre": [0.0, 0.0], "width_m": 13.0}
TOPZ = {"name": "topzoom", "ortho": True, "centre": [0.0, 0.2], "width_m": 6.0}
ISO = {"name": "iso", "position": [-7.5, -1.8, 7.0], "look_at": [0.6, 0.1, 0.0], "focal": 18.0}
CLOSE = {"name": "close", "position": [-4.0, -0.8, 2.4], "look_at": [0.0, 0.4, 0.5], "focal": 18.0}
HERO = {"name": "hero", "position": [2.6, -0.45, 1.55], "look_at": [-0.3, 0.45, 0.45], "focal": 16.0}
# The corridor recording camera (video): above the corridor, looking along it.
REC_CORRIDOR = {"position": [-3.8, -0.4, 6.5], "look_at": [0.6, 0.2, 0.0], "focal_length": 18.0}  # above the corridor: no wall hides the AMR

# Cross scene (24 x 16 m bay). Ortho 30 m wide = scene_shots.py plan, so
# scripts/scenario_figure.py can draw the missions on it.
X_TOP = {"name": "top", "ortho": True, "centre": [0.0, 0.0], "width_m": 30.0}
X_ISO_SE = {"name": "iso_se", "position": [16.0, -14.0, 11.0], "look_at": [0.0, 0.0, 1.0], "focal": 20.0}
X_ISO_NW = {"name": "iso_nw", "position": [-16.0, 13.0, 11.0], "look_at": [0.0, 0.5, 1.0], "focal": 20.0}
X_CROSSING = {"name": "crossing", "ortho": True, "centre": [6.0, 0.0], "width_m": 12.0}
X_CROWD = {"name": "crowd", "position": [0.0, -7.2, 3.6], "look_at": [0.0, -1.5, 0.8], "focal": 20.0}
X_NORTH = {"name": "north_aisle", "position": [11.5, 4.21, 1.9], "look_at": [-10.0, 4.21, 0.9], "focal": 22.0}


def cond_path(variant: str, kind: str, value: float) -> str:
    d = "configs/stage1a/" + VARIANTS[variant]["cond_dir"]
    p = PROJECT_ROOT / d / f"{condition_name(kind, value)}.yaml"
    if not p.exists():
        raise FileNotFoundError(p)
    return str(p.relative_to(PROJECT_ROOT))


def value_for(env: str, kind: str, e: float) -> float:
    cfg = load_config(common_path=env)
    return round(fz.value_for_extent(cfg, kind, e, "a"), 2)


def capture_cfg(name: str, base: str, camera: dict) -> str:
    d = PROJECT_ROOT / "configs" / "captures" / VERSION
    d.mkdir(parents=True, exist_ok=True)
    p = d / f"{name}.yaml"
    p.write_text("# CAPTURE ONLY -- not a measurement condition. Generated by\n"
                 "# scripts/paper_capture_plan.py. Only the recording camera and\n"
                 "# recording.version differ from the base config.\n"
                 + yaml.safe_dump({"base": base, "recording": {
                     "version": VERSION, "resolution": [1920, 1080], "camera": camera}},
                     sort_keys=False), encoding="utf-8")
    return str(p.relative_to(PROJECT_ROOT))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--final-variant", required=True, choices=sorted(VARIANTS))
    ap.add_argument("--root", default=f"results/captures/{VERSION}")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    fv = args.final_variant
    fbuf = VARIANTS[fv]["buffer"]
    root = PROJECT_ROOT / args.root
    raw = f"{args.root}/raw"
    sel = json.loads((PROJECT_ROOT / "results/batches/261114_stage1a_final/buffer_selection.json").read_text())
    model = json.loads((PROJECT_ROOT / f"configs/stage1a/model_exec_{fv}.json").read_text())
    jobs = []

    def job(name, config, scenario, overlays, views, amr_pose=None):
        jobs.append((name, {"config": config, "scenario": scenario, "amr_pose": amr_pose, "out": raw,
                            "prefix": name, "overlays": overlays, "views": views}))

    # A. environment, every width, same cameras, no Comfort Space
    for w in (1.5, 1.8, 2.2, 2.6):
        job(f"S1_env_W{int(round(w * 10)):02d}", ENV.format(w=w, c="c3"), None,
            [{"tag": "clean", "comfort": False}], [TOP, ISO, CLOSE])
    job("S1_env_W22_human_amr", ENV.format(w=2.2, c="c3"), None,
        [{"tag": "clean", "comfort": False}], [CLOSE, HERO, ISO], amr_pose=[-1.3, 0.0, 0.0])

    # B. Static Comfort Space at W 2.2, e = 0.72 (passed in every buffer setting)
    env22 = ENV.format(w=2.2, c="c3")
    st = cond_path(fv, "static", value_for(env22, "static", 0.72))
    job("S1_static_W22", env22, st,
        [{"tag": "human_only", "comfort": False, "amr": False},
         {"tag": "static", "amr": False},
         {"tag": "static_amr", "amr": True}],
        [TOP, TOPZ, ISO, CLOSE, HERO], amr_pose=[-1.3, 0.0, 0.0])

    # C / D / O. B3-O contexts, same target size 1.20 m, same person, AMR, cameras
    for c in ("c1", "c2", "c3", "c4"):
        env = ENV.format(w=2.2, c=c)
        overlay = write_capture_condition(root, "b3o", 1.20, fbuf)
        job(f"S1_context_{c.upper()}", env, overlay,
            [{"tag": "b3o", "amr": True}, {"tag": "b3o_noamr", "amr": False}],
            [TOP, TOPZ, ISO, CLOSE, HERO], amr_pose=[-1.3, 0.0, 0.0])

    # F (still). The three buffer settings drawn on one scene: W 2.0 Static e 0.81
    env20 = ENV.format(w=2.0, c="c3")
    v081 = value_for(env20, "static", 0.81)
    job("S1_buffer_still_W20", env20, cond_path(fv, "static", v081),
        [{"tag": "buf000", "buffer": 0.0, "amr": False},
         {"tag": f"buf{int(round(fbuf * 100)):03d}", "buffer": fbuf, "amr": False},
         {"tag": "buf035", "buffer": 0.35, "amr": False}],
        [TOP, TOPZ, ISO])

    # K / L. cross scene, seed 2 (the diagnostic pair), B3-O and Static drawn
    camp2 = "configs/campaigns/cross/campaign_h8_a3_cross_s2.yaml"
    xover_b3o = "configs/stage3/b3o_initial.yaml"
    xover_st = "configs/stage3/static_baseline.yaml"
    job("CROSS_s002_overview", camp2, xover_b3o,
        [{"tag": "b3o", "buffer": fbuf}, {"tag": "clean", "comfort": False}],
        [X_TOP, X_ISO_SE, X_ISO_NW, X_CROSSING, X_CROWD, X_NORTH])
    job("CROSS_s002_static", camp2, xover_st, [{"tag": "b2static", "buffer": fbuf}],
        [X_TOP, X_ISO_SE, X_CROSSING, X_NORTH])
    # M / N. plain plans of the other seeds the existing examples ran on
    # (seed 3: the second diagnostic pair and the size-sweep nav2_abort;
    # seed 5: the size-sweep post_evade_stall), for trajectory overlays
    for seed in (3, 5):
        job(f"CROSS_s{seed:03d}_gallery", f"configs/campaigns/cross/campaign_h8_a3_cross_s{seed}.yaml", None,
            [{"tag": "clean", "comfort": False}], [X_TOP])

    # Recorded capture runs (video + costmap video).
    runs = []
    rec_c = lambda base, tag: capture_cfg(tag, base, REC_CORRIDOR)  # noqa: E731
    # E / J: final buffer, W 2.2 Static: far below, last pass, first fail (from the final model)
    pw = {w["aisle_width_m"]: w for w in model["per_width"]}[2.2]
    lo, hi = pw["R_exec_lo"], pw["R_exec_hi"]
    cfg22 = rec_c(env22, "rec_W22")
    for tag, e in (("E_small", 0.42), ("E_lastpass", lo), ("E_firstfail", hi)):
        runs.append((cond_path(fv, "static", value_for(env22, "static", e)), cfg22, f"S1_{tag}_W22_e{e:.2f}"))
    # F / G / H / I: same scene, W 2.0 Static e 0.81, three buffers
    cfg20 = rec_c(env20, "rec_W20")
    runs.append((cond_path("nobuf", "static", v081), cfg20, "S1_buffer_000_W20_e0.81"))
    runs.append((cond_path(fv, "static", v081), cfg20, f"S1_buffer_{int(round(fbuf * 100)):03d}_W20_e0.81"))
    runs.append((cond_path("default", "static", v081) if (PROJECT_ROOT / "configs/stage1a/conditions" /
                 f"static_r{v081:.2f}.yaml").exists() else write_capture_condition(root, "static", v081, 0.35),
                 cfg20, "S1_buffer_035_W20_e0.81"))
    # M / L: cross seed 2 (and 3), diagnostic buffer 0, B2 hold vs B3-O pass
    for seed, look in ((2, (5.0, 4.2)), (3, (-1.0, 4.0))):
        cam = {"position": [look[0] - 0.5, look[1] - 5.2, 7.5], "look_at": [look[0], look[1], 0.0],
               "focal_length": 18.0}
        cc = capture_cfg(f"rec_cross_s{seed}", f"configs/campaigns/cross/campaign_h8_a3_cross_s{seed}.yaml", cam)
        runs.append(("configs/stage1a/diagnostic/diag_nobuffer_static_r1.20_cross.yaml", cc,
                     f"CROSS_s{seed:03d}_B2_diagnostic"))
        runs.append(("configs/stage1a/diagnostic/diag_nobuffer_b3o_r1.20_cross.yaml", cc,
                     f"CROSS_s{seed:03d}_B3O_diagnostic"))

    if args.check:
        for n, j in jobs:
            print("still", n, j["scenario"])
        for r in runs:
            print("run", *r)
        return 0
    (root / "jobs").mkdir(parents=True, exist_ok=True)
    for n, j in jobs:
        (root / "jobs" / f"still_{n}.json").write_text(json.dumps(j, indent=2))
    (root / "runs.txt").write_text("# scenario-overlay capture-config tag  (capture runs, not measurements)\n"
                                   + "\n".join(" ".join(r) for r in runs) + "\n")
    (root / "plan.json").write_text(json.dumps({"final_variant": fv, "final_buffer_m": fbuf,
                                                "selection": sel.get("selected"),
                                                "W22_bracket": [lo, hi]}, indent=2))
    print(f"{len(jobs)} still jobs, {len(runs)} capture runs -> {root}")
    return 0


def write_capture_condition(root: Path, kind: str, value: float, buffer: float) -> str:
    """A capture-only condition overlay (scenario + comfort_space, like Stage 1's)."""
    d = root / "overlays"
    d.mkdir(parents=True, exist_ok=True)
    p = write_condition(d, kind, value, stage="capture only")
    text = p.read_text(encoding="utf-8")
    if "buffer_width" not in text:
        p.write_text("# CAPTURE ONLY (scripts/paper_capture_plan.py), costmap buffer "
                     f"{buffer} m.\n" + text + f"  costmap:\n    buffer_width: {buffer}\n", encoding="utf-8")
    return str(p.relative_to(PROJECT_ROOT))


if __name__ == "__main__":
    sys.exit(main())
