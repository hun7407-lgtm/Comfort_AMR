#!/usr/bin/env python3
"""Stage 2 uniform-scale sweep: write envs, conditions, manifest, plan.

    python3 scripts/stage2scale_plan.py --config configs/stage2scale/stage2scale_v2_nav2only.yaml --phase pilot --check
    python3 scripts/stage2scale_plan.py --config ... --phase pilot      # -> <batch_prefix>_pilot
    python3 scripts/stage2scale_plan.py --config ... --phase coarse     # needs `frozen` geometry
    python3 scripts/stage2scale_plan.py --config ... --phase confirm    # needs `frozen` + `confirm_conditions`

Plain Python 3. Writes into the yaml's `out_dir` (never the v1 folder):
    <out_dir>/conditions/{B1,B2_r<R>,S3_a<alpha>}.yaml
    <out_dir>/envs/<scenario>_<geometry>.yaml
    <batch>/manifest.tsv (trial_id, repeat, condition, config), <batch>/plan.json

Refuses to write when
  * a normalised template's max extent != anchor, bounding radius > anchor,
    E(alpha)/E(1) != alpha on an axis, or an axis is below min_radius;
  * for a scenario x geometry, B1 / B2 / any alpha differ in anything but
    the Comfort Space policy (physical signature incl. control mode, buffer);
  * control.mode nav2_only and the merged config breaks it (control_mode.py);
  * MV-P: walker and AMR share a lane or do not travel in opposite directions.
History: v1 (2026-11-26, configs/stage2scale/stage2scale.yaml, legacy gate) was
generated by the first version of this script; its configs and smoke batch are
kept as they are. Design: docs/STAGE2_UNIFORM_SCALE_PROTOCOL.md,
docs/NAV2_ONLY_STAGE2_MAIN_EXPERIMENT_SPEC.md.
"""

from __future__ import annotations

import argparse
import json
import random
import shutil
import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

import yaml  # noqa: E402

from comfort_core import comfort_reference as cref  # noqa: E402
from comfort_core import control_mode as cm  # noqa: E402
from comfort_core import stage2scale as s2  # noqa: E402
from comfort_core.config import load_config  # noqa: E402
from comfort_core.contexts import facing_deg  # noqa: E402

DEFAULT_CFG = PROJECT_ROOT / "configs" / "stage2scale" / "stage2scale_v2_nav2only.yaml"


def atag(a: float) -> str:
    return f"{a:.2f}"


def shapes(S: dict, base: dict) -> dict:
    cs = base["comfort_space"]
    raw = s2.raw_templates(cs, float(S["moving_reference_speed_mps"]))
    norm = s2.normalise(raw, float(S["anchor_m"]))
    mr = float(cs["min_radius"])
    alphas = s2.alpha_grid(norm, mr) if S["alphas"] == "auto" else [float(a) for a in S["alphas"]]
    return {"raw": raw, "normalised": norm, "min_radius_m": mr, "alphas": alphas,
            "min_alpha_without_clip": s2.min_alpha_without_clip(norm, mr),
            "heading_min_speed_mps": float(cs["directional"]["moving"].get("heading_min_speed_mps", 0.1))}


def check_shapes(S: dict, sh: dict) -> list:
    probs = []
    anchor, norm = float(S["anchor_m"]), sh["normalised"]
    for st, e in norm.items():
        if abs(max(e.values()) - anchor) > 1e-9:
            probs.append(f"{st}: max extent {max(e.values())} != {anchor}")
        if s2.bounding_radius(e) > anchor + 1e-6:
            probs.append(f"{st}: bounding radius > {anchor}")
        raw = sh["raw"][st]
        for a in s2.AXES:
            if abs(e[a] / e["front"] - raw[a] / raw["front"]) > 1e-12:
                probs.append(f"{st}: ratio {a}/front changed by normalisation")
    for al in sh["alphas"]:
        ex = s2.scaled(norm, al)
        for st in norm:
            for a in s2.AXES:
                if abs(ex[st][a] / norm[st][a] - al) > 1e-12:
                    probs.append(f"alpha {al} {st} {a}: not a pure multiple")
                if ex[st][a] < sh["min_radius_m"] - 1e-9:
                    probs.append(f"alpha {al} {st} {a} = {ex[st][a]:.4f} < min_radius: would be clipped")
    return probs


def b2_name(S):
    return f"B2_r{float(S['anchor_m']):.3f}"


def conditions(S: dict, sh: dict) -> dict:
    out = {"B1": ("B1 no Comfort Space", {"policy": "none"}, None)}
    r = float(S["anchor_m"])
    out[b2_name(S)] = (f"B2 static circle {r:.3f} m (R_ref, {S['anchor_provenance']})",
                       {"policy": "static", "static_radius": r, "aisle_scaling": {"enabled": False, "scale": 1.0}}, None)
    for al in sh["alphas"]:
        ex = s2.scaled(sh["normalised"], al)
        lab = "; ".join(f"{st} F{ex[st]['front']:.3f} S{ex[st]['side']:.3f} R{ex[st]['rear']:.3f}" for st in s2.STATES)
        out[f"S3_a{atag(al)}"] = (f"State-wise uniform scale alpha {atag(al)} of R_ref {r:.3f} ({lab})",
                                  s2.comfort_block(ex, sh["heading_min_speed_mps"]), al)
    return out


def resolve(names, conds, S, sh):
    out = []
    for c in names:
        c = str(c)
        if c == "B1":
            out.append("B1")
        elif c == "B2":
            out.append(b2_name(S))
        elif c == "all":
            out += [f"S3_a{atag(a)}" for a in sh["alphas"]]
        elif c == "min":
            out.append(f"S3_a{atag(min(sh['alphas']))}")
        else:
            out.append(f"S3_a{atag(float(c))}")
    bad = [n for n in out if n not in conds]
    if bad:
        raise SystemExit(f"[ERROR] unknown conditions {bad} (alpha grid {sh['alphas']})")
    return list(dict.fromkeys(out))


def geometries(S: dict, phase: dict, name: str, sc: dict) -> list:
    G = S["geometry"]
    frozen = (S.get("frozen") or {}).get(name)
    if sc["state"] == "moving":
        m = G["moving"]
        if phase["geometry"] == "frozen":
            if not frozen:
                raise SystemExit(f"[ERROR] no frozen geometry for {name} (pilot first)")
            combos = [(frozen["width_m"], frozen["lane_gap_m"])]
        else:
            combos = [(w, g) for w in phase["moving_widths"] for g in phase["moving_lane_gaps"]]
        out = []
        for w, gp in combos:
            ov = s2.moving_env(m, float(w), float(gp))
            lanes = ov.pop("_lanes")
            out.append((f"w{w:.2f}_g{gp:.2f}", ov, {"width_m": w, **lanes}))
        return out
    g = G["static"]
    if phase["geometry"] == "frozen":
        if not frozen:
            raise SystemExit(f"[ERROR] no frozen geometry for {name} (pilot first)")
        widths = [frozen["width_m"]]
    else:
        widths = phase["static_widths"]
    f = facing_deg(sc["context"], -90.0)
    f = ((f + 180.0) % 360.0) - 180.0
    return [(f"w{w:.2f}", s2.static_env(sc, g, float(w), f), {"width_m": w, "facing_deg": f}) for w in widths]


def env_text(S, name: str, sc: dict, gid: str, ov: dict, control: dict) -> str:
    doc = {"base": "configs/common.yaml",
           "scenario_meta": {"scenario_id": f"stage2scale_{S['version']}_{name}_{gid}",
                             "stage": f"Stage 2 uniform scale {S['version']}",
                             "label": sc["label"], "human_count": 1, "amr_count": 1,
                             "aisle_width_m": ov["corridor"]["width"]},
           **ov,
           "stations": {"a": {"enabled": False}, "b": {"enabled": False}},
           "fleet": {"enabled": False}}
    for k, v in control.items():
        if k == "navigation":
            doc["navigation"] = {**doc["navigation"], **v}
        else:
            doc[k] = v
    return (f"# GENERATED by scripts/stage2scale_plan.py from {S['_cfg_rel']} -- do not hand-edit.\n"
            f"# {sc['label']} -- geometry {gid}\n" + yaml.safe_dump(doc, sort_keys=False))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=str(DEFAULT_CFG))
    ap.add_argument("--phase", required=True)
    ap.add_argument("--check", action="store_true", help="verify and print; write nothing")
    args = ap.parse_args()
    cfgp = Path(args.config).resolve()
    S = yaml.safe_load(cfgp.read_text())
    S["_cfg_rel"] = str(cfgp.relative_to(PROJECT_ROOT))
    phase = S["phases"][args.phase]
    base = load_config(common_path=str(PROJECT_ROOT / "configs" / "common.yaml"))
    control = yaml.safe_load((PROJECT_ROOT / S["control_overlay"]).read_text()) if S.get("control_overlay") else {}
    OUT = PROJECT_ROOT / S["out_dir"]

    sh = shapes(S, base)
    probs = check_shapes(S, sh)
    if probs:
        print("[ERROR] shape checks failed:\n  " + "\n  ".join(probs))
        return 1
    conds = conditions(S, sh)
    files = {}
    for cn, (label, cs, _a) in conds.items():
        files[OUT / "conditions" / f"{cn}.yaml"] = (
            f"# GENERATED by scripts/stage2scale_plan.py from {S['_cfg_rel']} -- do not hand-edit.\n"
            + yaml.safe_dump({"scenario": {"name": f"S2S{S['version']}_{cn}", "label": label}, "comfort_space": cs},
                             sort_keys=False))
    try:
        commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=PROJECT_ROOT, capture_output=True,
                                text=True).stdout.strip()
    except Exception:       # noqa: BLE001
        commit = None
    plan = {"version": S["version"], "phase": args.phase, "config": S["_cfg_rel"], "commit_at_plan": commit,
            "control_mode": (control.get("control") or {}).get("mode", cm.LEGACY),
            "anchor_m": S["anchor_m"], "anchor_provenance": S["anchor_provenance"], "alphas": sh["alphas"],
            "moving_reference_speed_mps": S["moving_reference_speed_mps"],
            "templates_raw": sh["raw"], "templates_normalised": sh["normalised"],
            "min_radius_m": sh["min_radius_m"], "min_alpha_without_clip": sh["min_alpha_without_clip"],
            "extents_by_alpha": {atag(a): s2.scaled(sh["normalised"], a) for a in sh["alphas"]},
            "conditions": {cn: {"label": v[0], "alpha": v[2]} for cn, v in conds.items()},
            "reference": S["reference"], "criteria": S["criteria"], "references": cref.describe(),
            "amr_half_length_m": float(base["amr"]["footprint_length"]) / 2.0,
            "amr_half_width_m": float(base["amr"]["footprint_width"]) / 2.0,
            "human_radius_m": float(base["humans"]["radius"]),
            "frozen": S.get("frozen"), "scenarios": {}, "geometries": {}}
    lines = []
    for name, sc in S["scenarios"].items():
        entry = {k: sc.get(k) for k in ("state", "context", "intended_sector", "primary", "label")}
        if sc.get("feasibility") == "overtake":
            ov = S["overtake"]
            ok = ov["amr_max_speed_mps"] - ov["walker_speed_mps"] > 0
            entry["status"] = "RUN" if ok else "INFEASIBLE"
            entry["feasibility"] = {**ov, "note": "AMR max speed <= walker animation speed: cannot overtake; "
                                                  "no numeric overtaking comfort curve either"}
            plan["scenarios"][name] = entry
            if not ok:
                continue
        entry["status"] = "RUN"
        plan["scenarios"][name] = entry
        want = (S.get("confirm_conditions") or {}).get(name) if phase.get("conditions") == "confirm" else phase["conditions"]
        if want is None:
            raise SystemExit(f"[ERROR] no confirm_conditions for {name}")
        run_conds = resolve(want, conds, S, sh)
        entry["run_conditions"] = run_conds
        reps = int(phase.get("moving_repeats", phase["repeats"])) if sc["state"] == "moving" else int(phase["repeats"])
        for gid, ov, meta in geometries(S, phase, name, sc):
            env_name = f"{name}_{gid}"
            files[OUT / "envs" / f"{env_name}.yaml"] = env_text(S, name, sc, gid, ov, control)
            plan["geometries"][env_name] = {"scenario": name, "geometry": gid, **meta,
                                            "start": ov["navigation"]["start"], "goal": ov["navigation"]["goal"],
                                            "person": ov["humans"]["a"]}
            for rep in range(1, reps + 1):
                for cn in run_conds:
                    tid = f"{name}_{gid}_{cn}_rep{rep:02d}"
                    rel = OUT.relative_to(PROJECT_ROOT)
                    lines.append((rep, f"{tid}\t{rep}\t{rel}/conditions/{cn}.yaml\t{rel}/envs/{env_name}.yaml"))

    root = OUT / ".check" if args.check else OUT
    for p, text in files.items():
        q = root / p.relative_to(OUT)
        q.parent.mkdir(parents=True, exist_ok=True)
        if not args.check and q.exists() and q.read_text() != text and S.get("immutable_outputs", True):
            # same name, different content: never silently change a config a batch already used
            print(f"[ERROR] {q.relative_to(PROJECT_ROOT)} exists with different content; bump `version`/out_dir")
            return 1
        q.write_text(text, encoding="utf-8")

    from comfort_core.layout import validate
    errors = []
    for env_name, gm in plan["geometries"].items():
        envp = root / "envs" / f"{env_name}.yaml"
        sigs = {}
        for cn in conds:
            cfg = load_config(scenario=str(root / "conditions" / f"{cn}.yaml"), common_path=str(envp))
            sigs[cn] = s2.physical_signature(cfg)
            for pr in cm.config_problems(cfg):
                errors.append(f"{env_name} {cn}: {pr}")
        if len(set(sigs.values())) != 1:
            errors.append(f"{env_name}: physical configs differ between conditions {sigs}")
        gm["physical_signature"] = next(iter(sigs.values()))
        pv = validate(load_config(common_path=str(envp)))
        if pv:
            errors.append(f"{env_name}: layout {pv}")
        if plan["scenarios"][gm["scenario"]]["state"] == "moving":
            hy, ay, p = gm["human_lane_y"], gm["amr_lane_y"], gm["person"]
            if not abs(hy - ay) > 1e-6:
                errors.append(f"{env_name}: walker and AMR share a lane")
            if not (p["route"][0][0] - p["position"][0]) * (gm["goal"][0] - gm["start"][0]) < 0:
                errors.append(f"{env_name}: not opposite directions")
            if p["route"][0][1] != hy or gm["start"][1] != gm["goal"][1]:
                errors.append(f"{env_name}: lanes not straight")
    if args.check:
        shutil.rmtree(root)
    if errors:
        print("[ERROR]\n  " + "\n  ".join(errors))
        return 1

    by_rep = {}
    for rep, line in lines:
        by_rep.setdefault(rep, []).append(line)
    manifest = []
    for rep in sorted(by_rep):
        block = by_rep[rep]
        random.Random(1000 + rep).shuffle(block)
        manifest += block
    batch = PROJECT_ROOT / f"{S['batch_prefix']}_{args.phase}"
    print(f"{S['version']} phase {args.phase}: anchor {S['anchor_m']} ({S['anchor_provenance']}), "
          f"alphas {sh['alphas']}, control {plan['control_mode']}")
    print(f"  {len(plan['geometries'])} geometries, {len(manifest)} trials -> {batch.relative_to(PROJECT_ROOT)}")
    for st, e in sh["normalised"].items():
        print(f"  {st:16s} alpha=1 F/S/R {[round(e[a], 4) for a in s2.AXES]}")
    for n, e in plan["scenarios"].items():
        print(f"  {n:5s} {e['status']} {e.get('run_conditions', '')}")
    if args.check:
        print("check OK (nothing written)")
        return 0
    batch.mkdir(parents=True, exist_ok=True)
    text = (f"# Stage 2 uniform scale {S['version']} {args.phase}\n# trial_id\trepeat\tcondition\tconfig\n"
            + "\n".join(manifest) + "\n")
    mf = batch / "manifest.tsv"
    if mf.exists() and mf.read_text() != text and any((batch / "trials").glob("*/DONE")):
        print("[ERROR] batch has finished trials and a different manifest; not overwriting")
        return 1
    mf.write_text(text)
    (batch / "plan.json").write_text(json.dumps(plan, indent=1))
    print("written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
