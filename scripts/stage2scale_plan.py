#!/usr/bin/env python3
"""Stage 2 uniform-scale sweep: write envs, conditions, manifest, plan.

    python3 scripts/stage2scale_plan.py --check              # verify + print, write nothing
    python3 scripts/stage2scale_plan.py --phase smoke        # -> <batch_prefix>_smoke
    python3 scripts/stage2scale_plan.py --phase pilot
    python3 scripts/stage2scale_plan.py --phase coarse       # refuses until widths / lane gap are frozen

Plain Python 3. Reads configs/stage2scale/stage2scale.yaml. Writes
    configs/stage2scale/conditions/{B1,B2_r0.900,S3_a<alpha>}.yaml
    configs/stage2scale/envs/<scenario>_<geometry>.yaml
    <batch>/manifest.tsv (trial_id, repeat, condition, config), <batch>/plan.json

Before writing anything it checks (and refuses on failure):
  * normalised templates: max extent = anchor, bounding radius <= anchor;
    E(alpha) / E(1) == alpha on every axis; no axis below min_radius;
  * per scenario x geometry: the merged configs of B1, B2 and every alpha
    have the same physical signature (everything but comfort_space and
    the scenario label);
  * MV-P: walker and AMR lanes differ, opposite travel directions.
Design: docs/STAGE2_UNIFORM_SCALE_PROTOCOL.md.
"""

from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

import yaml  # noqa: E402

from comfort_core import comfort_reference as cref  # noqa: E402
from comfort_core import stage2scale as s2  # noqa: E402
from comfort_core.config import load_config  # noqa: E402
from comfort_core.contexts import facing_deg  # noqa: E402

CFG = PROJECT_ROOT / "configs" / "stage2scale" / "stage2scale.yaml"
OUT = PROJECT_ROOT / "configs" / "stage2scale"
HEADER = ("# GENERATED by scripts/stage2scale_plan.py from configs/stage2scale/stage2scale.yaml\n"
          "# -- regenerate, do not hand-edit. Stage 2 uniform-scale sweep.\n")


def atag(a: float) -> str:
    return f"{a:.2f}"


def shapes(S: dict, base: dict) -> dict:
    cs = base["comfort_space"]
    raw = s2.raw_templates(cs, float(S["moving_reference_speed_mps"]))
    norm = s2.normalise(raw, float(S["anchor_m"]))
    return {"raw": raw, "normalised": norm, "min_radius_m": float(cs["min_radius"]),
            "min_alpha_without_clip": s2.min_alpha_without_clip(norm, float(cs["min_radius"])),
            "heading_min_speed_mps": float(cs["directional"]["moving"].get("heading_min_speed_mps", 0.1))}


def check_shapes(S: dict, sh: dict) -> list:
    probs = []
    anchor, norm = float(S["anchor_m"]), sh["normalised"]
    for st, e in norm.items():
        if abs(max(e.values()) - anchor) > 1e-9:
            probs.append(f"{st}: max extent {max(e.values())} != {anchor}")
        br = s2.bounding_radius(e)
        if br > anchor + 1e-6:
            probs.append(f"{st}: bounding radius {br:.6f} > {anchor}")
        raw = sh["raw"][st]
        for a in s2.AXES:
            if abs(e[a] / e["front"] - raw[a] / raw["front"]) > 1e-12:
                probs.append(f"{st}: ratio {a}/front changed by normalisation")
    for al in S["alphas"]:
        ex = s2.scaled(norm, al)
        for st in norm:
            for a in s2.AXES:
                if abs(ex[st][a] / norm[st][a] - al) > 1e-12:
                    probs.append(f"alpha {al} {st} {a}: not a pure multiple")
                if ex[st][a] < sh["min_radius_m"] - 1e-9:
                    probs.append(f"alpha {al} {st} {a} = {ex[st][a]:.4f} < min_radius {sh['min_radius_m']}: "
                                 "would be clipped, ratio not preserved")
    return probs


def conditions(S: dict, sh: dict) -> dict:
    """name -> (label, comfort_space overlay, alpha or None)."""
    out = {}
    if S.get("include_b1", True):
        out["B1"] = ("B1 no Comfort Space", {"policy": "none"}, None)
    r = float(S["b2_radius_m"])
    out[f"B2_r{r:.3f}"] = (f"B2 static circle {r:.3f} m",
                           {"policy": "static", "static_radius": r, "aisle_scaling": {"enabled": False, "scale": 1.0}},
                           None)
    for al in S["alphas"]:
        ex = s2.scaled(sh["normalised"], al)
        lab = "; ".join(f"{st} F{ex[st]['front']:.3f} S{ex[st]['side']:.3f} R{ex[st]['rear']:.3f}"
                        for st in s2.STATES)
        out[f"S3_a{atag(al)}"] = (f"State-wise uniform scale alpha {atag(al)} ({lab})",
                                  s2.comfort_block(ex, sh["heading_min_speed_mps"]), al)
    return out


def wanted_conditions(phase: dict, conds: dict, S: dict) -> list:
    names = []
    for c in phase["conditions"]:
        if c == "B1":
            names.append("B1")
        elif c == "B2":
            names.append(f"B2_r{float(S['b2_radius_m']):.3f}")
        elif c == "all":
            names += [f"S3_a{atag(a)}" for a in S["alphas"]]
        else:
            names.append(f"S3_a{atag(float(c))}")
    missing = [n for n in names if n not in conds]
    if missing:
        raise SystemExit(f"[ERROR] phase asks for unknown conditions {missing}")
    return names


def geometries(S: dict, phase: dict, name: str, sc: dict) -> list:
    """[(geom_id, overlay, meta)] for one scenario in this phase."""
    G = S["geometry"]
    if sc["state"] == "moving":
        m = G["moving"]
        if phase["moving_lane_gaps"] == "candidates":
            gaps = m["lane_gap_candidates_m"]
        else:
            if m.get("lane_gap_m") is None:
                raise SystemExit("[ERROR] geometry.moving.lane_gap_m is not frozen (pilot first)")
            gaps = [m["lane_gap_m"]]
        mode = phase["static_widths"]
        if mode == "smoke":
            widths = [m["smoke_width_m"]]
        elif mode == "candidates":
            widths = m["width_candidates_m"]
        else:
            if m.get("tight_width_m") is None:
                raise SystemExit("[ERROR] geometry.moving.tight_width_m is not frozen (pilot first)")
            widths = [m["tight_width_m"]]
        out = []
        for w in widths:
            for gp in gaps:
                ov = s2.moving_env(m, float(w), float(gp))
                lanes = ov.pop("_lanes")
                out.append((f"w{w:.2f}_g{gp:.2f}", ov, {"width_m": w, **lanes}))
        return out
    g = G["static"]
    mode = phase["static_widths"]
    if mode == "smoke":
        widths = [g["smoke_width_m"]]
    elif mode == "candidates":
        widths = g["width_candidates_m"]
    else:
        if g.get("tight_width_m") is None:
            raise SystemExit("[ERROR] geometry.static.tight_width_m is not frozen (pilot first)")
        widths = [g["tight_width_m"]]
    f = facing_deg(sc["context"], -90.0)
    f = ((f + 180.0) % 360.0) - 180.0
    return [(f"w{w:.2f}", s2.static_env(sc, g, float(w), f), {"width_m": w, "facing_deg": f}) for w in widths]


def env_text(name: str, sc: dict, gid: str, ov: dict) -> str:
    doc = {"base": "configs/common.yaml",
           "scenario_meta": {"scenario_id": f"stage2scale_{name}_{gid}", "stage": "Stage 2 uniform scale",
                             "label": sc["label"], "human_count": 1, "amr_count": 1,
                             "aisle_width_m": ov["corridor"]["width"]},
           **ov,
           "stations": {"a": {"enabled": False}, "b": {"enabled": False}},
           "fleet": {"enabled": False}}
    return HEADER + f"# {sc['label']} -- geometry {gid}\n" + yaml.safe_dump(doc, sort_keys=False)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--phase", default="smoke", choices=["smoke", "pilot", "coarse"])
    ap.add_argument("--check", action="store_true", help="verify and print; write nothing")
    args = ap.parse_args()
    S = yaml.safe_load(CFG.read_text())
    phase = S["phases"][args.phase]
    base = load_config(common_path=str(PROJECT_ROOT / "configs" / "common.yaml"))

    sh = shapes(S, base)
    probs = check_shapes(S, sh)
    if probs:
        print("[ERROR] shape checks failed:\n  " + "\n  ".join(probs))
        return 1
    conds = conditions(S, sh)
    run_conds = wanted_conditions(phase, conds, S)

    files = {}
    for cn, (label, cs, _a) in conds.items():
        files[OUT / "conditions" / f"{cn}.yaml"] = (
            HEADER + yaml.safe_dump({"scenario": {"name": f"S2S_{cn}", "label": label}, "comfort_space": cs},
                                    sort_keys=False))

    plan = {"version": S["version"], "phase": args.phase, "anchor_m": S["anchor_m"], "alphas": S["alphas"],
            "moving_reference_speed_mps": S["moving_reference_speed_mps"],
            "templates_raw": sh["raw"], "templates_normalised": sh["normalised"],
            "min_radius_m": sh["min_radius_m"], "min_alpha_without_clip": sh["min_alpha_without_clip"],
            "extents_by_alpha": {atag(a): s2.scaled(sh["normalised"], a) for a in S["alphas"]},
            "conditions": {cn: {"label": v[0], "alpha": v[2]} for cn, v in conds.items()},
            "reference": S["reference"], "criteria": S["criteria"], "references": cref.describe(),
            "amr_half_length_m": float(base["amr"]["footprint_length"]) / 2.0,
            "amr_half_width_m": float(base["amr"]["footprint_width"]) / 2.0,
            "human_radius_m": float(base["humans"]["radius"]),
            "scenarios": {}, "geometries": {}}
    lines = []      # (repeat, trial line)
    for name, sc in S["scenarios"].items():
        entry = {k: sc.get(k) for k in ("state", "context", "intended_sector", "primary", "label")}
        if sc.get("feasibility") == "overtake":
            ov = S["overtake"]
            dv = ov["amr_max_speed_mps"] - ov["walker_speed_mps"]
            entry["status"] = "RUN" if dv > 0 else "INFEASIBLE"
            entry["feasibility"] = {**ov, "note": "AMR max speed <= walker animation speed: cannot overtake; "
                                                  "no numeric overtaking comfort curve either"}
            plan["scenarios"][name] = entry
            if dv <= 0:
                continue
        entry["status"] = "RUN"
        plan["scenarios"][name] = entry
        reps = int(phase.get("moving_repeats", phase["repeats"])) if sc["state"] == "moving" else int(phase["repeats"])
        for gid, ov, meta in geometries(S, phase, name, sc):
            env_name = f"{name}_{gid}"
            env_path = OUT / "envs" / f"{env_name}.yaml"
            files[env_path] = env_text(name, sc, gid, ov)
            plan["geometries"][env_name] = {"scenario": name, "geometry": gid, **meta,
                                            "start": ov["navigation"]["start"], "goal": ov["navigation"]["goal"],
                                            "person": ov["humans"]["a"]}
            for rep in range(1, reps + 1):
                for cn in run_conds:
                    tid = f"{name}_{gid}_{cn}_rep{rep:02d}"
                    lines.append((rep, env_name, f"{tid}\t{rep}\tconfigs/stage2scale/conditions/{cn}.yaml\t"
                                               f"configs/stage2scale/envs/{env_name}.yaml"))

    # write configs to a scratch copy first? No: generated configs are pure
    # functions of the yaml; write them, then verify, and refuse the batch on error.
    if args.check:
        tmp = PROJECT_ROOT / "configs" / "stage2scale" / ".check"
    else:
        tmp = None
    root = tmp or OUT
    for p, text in files.items():
        q = root / p.relative_to(OUT)
        q.parent.mkdir(parents=True, exist_ok=True)
        q.write_text(text, encoding="utf-8")

    # physical identity per scenario x geometry; layout validity; lanes
    from comfort_core.layout import validate
    errors = []
    for env_name, gmeta in plan["geometries"].items():
        envp = root / "envs" / f"{env_name}.yaml"
        sigs = {}
        for cn in conds:
            cfg = load_config(scenario=str(root / "conditions" / f"{cn}.yaml"), common_path=str(envp))
            sigs[cn] = s2.physical_signature(cfg)
        if len(set(sigs.values())) != 1:
            errors.append(f"{env_name}: physical configs differ between conditions {sigs}")
        gmeta["physical_signature"] = next(iter(sigs.values()))
        cfg = load_config(common_path=str(envp))
        pv = validate(cfg)
        if pv:
            errors.append(f"{env_name}: layout {pv}")
        if plan["scenarios"][gmeta["scenario"]]["state"] == "moving":
            hy, ay = gmeta["human_lane_y"], gmeta["amr_lane_y"]
            p = gmeta["person"]
            walk_dir = p["route"][0][0] - p["position"][0]
            amr_dir = gmeta["goal"][0] - gmeta["start"][0]
            if not abs(hy - ay) > 1e-6:
                errors.append(f"{env_name}: walker and AMR share a lane")
            if not walk_dir * amr_dir < 0:
                errors.append(f"{env_name}: walker and AMR do not travel in opposite directions")
            if p["route"][0][1] != hy or gmeta["start"][1] != gmeta["goal"][1]:
                errors.append(f"{env_name}: lanes not straight")
    if errors:
        print("[ERROR]\n  " + "\n  ".join(errors))
        return 1

    # interleaved order: repeat-major, conditions shuffled per repeat (fixed seed)
    by_rep = {}
    for rep, env_name, line in lines:
        by_rep.setdefault(rep, []).append(line)
    manifest = []
    for rep in sorted(by_rep):
        block = by_rep[rep]
        random.Random(1000 + rep).shuffle(block)
        manifest += block
    batch = PROJECT_ROOT / f"{S['batch_prefix']}_{args.phase}"
    print(f"phase {args.phase}: {len(conds)} conditions defined, running {run_conds}")
    print(f"  {len(plan['geometries'])} geometries, {len(manifest)} trials -> {batch.relative_to(PROJECT_ROOT)}")
    for st, e in sh["normalised"].items():
        print(f"  {st:16s} raw {[round(sh['raw'][st][a], 4) for a in s2.AXES]} -> "
              f"alpha=1 {[round(e[a], 4) for a in s2.AXES]} bounding {s2.bounding_radius(e):.4f}")
    print(f"  min alpha without clip {sh['min_alpha_without_clip']:.4f}")
    for n, e in plan["scenarios"].items():
        print(f"  {n:5s} {e['status']}")
    if args.check:
        import shutil
        shutil.rmtree(tmp)
        print("check OK (nothing written)")
        return 0
    batch.mkdir(parents=True, exist_ok=True)
    text = f"# Stage 2 uniform scale {S['version']} {args.phase}\n# trial_id\trepeat\tcondition\tconfig\n" \
           + "\n".join(manifest) + "\n"
    mf = batch / "manifest.tsv"
    if mf.exists() and mf.read_text() != text and any((batch / "trials").glob("*/DONE")):
        print("[ERROR] batch has finished trials and a different manifest; not overwriting")
        return 1
    mf.write_text(text)
    (batch / "plan.json").write_text(json.dumps(plan, indent=1))
    print("written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
