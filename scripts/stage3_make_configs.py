#!/usr/bin/env python3
"""Write the Stage 3 conditions: Static baseline, B3-O Initial, B3-O Optimized.

    python3 scripts/stage3_make_configs.py                       initial + static (1.20) + optimized TEMPLATE
    python3 scripts/stage3_make_configs.py --r-opt 1.0           optimized = B3-O geometry scaled to 1.00 m
    python3 scripts/stage3_make_configs.py --params my_b3o.yaml  optimized = explicit directional block
    python3 scripts/stage3_make_configs.py --static-size 1.2

Three scenario overlays in configs/stage3/ (only `scenario` and
`comfort_space`, so the campaign config is untouched):

    static_baseline.yaml   policy static, radius --static-size (1.20 m, the
                           historical B2 value, unless told otherwise)
    b3o_initial.yaml       policy state_directional, unscaled: the
                           literature-anchored engineering parameters in
                           configs/common.yaml comfort_space.directional,
                           exactly as the Stage 1 1.20 m condition
    b3o_optimized.yaml     the Stage 2 result. Two ways to express it:
                             --r-opt R       the whole geometry scaled to R
                                             (aisle_scaling target_size_m, as
                                             Stage 1 / Stage 2 do)
                             --params FILE   a YAML with a `directional:` block
                                             (and optionally min_radius) that
                                             replaces common.yaml's, for a
                                             calibration that changed the
                                             front/side/rear ratios too
                           Without either, a TEMPLATE with target_size_m null
                           is written and scripts/stage3_run.sh refuses to
                           run that condition until it is filled.

R_opt is a Stage 2 measurement. This script never invents one.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from comfort_core.config import load_with_base, resolve_path  # noqa: E402

HEADER = """\
# Stage 3 condition: {title}
#
# GENERATED by scripts/stage3_make_configs.py -- regenerate rather than
# hand-edit. ONLY `scenario` and `comfort_space` appear here; the campaign
# config (people, missions, timing, map, Nav2, safety layer) is identical
# for every Stage 3 condition of a seed.
#
{how}
#
# > Not a safety distance: the protective field is sized separately and
# > never changes with this.
"""


def write(name: str, title: str, how: str, body: dict, out_dir: Path) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{name}.yaml"
    text = yaml.safe_dump(body, sort_keys=False, default_flow_style=False)
    path.write_text(HEADER.format(title=title, how=how) + "\n" + text, encoding="utf-8")
    return path


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="configs/stage3")
    ap.add_argument("--static-size", type=float, default=1.20)
    ap.add_argument("--r-opt", type=float, default=None,
                    help="Stage 2 R_opt: B3-O geometry scaled so the moving front at 1.0 m/s is this")
    ap.add_argument("--params", default=None,
                    help="YAML with a `directional:` block (Stage 2 calibrated parameter set)")
    args = ap.parse_args()
    out = resolve_path(args.out)

    p = write("static_baseline",
              f"Static Comfort Space baseline, {args.static_size:.2f} m",
              "# One round space of this radius for everybody (the historical B2\n"
              "# condition at 1.20 m). Optional baseline for the paper comparison.",
              {"scenario": {"name": "static_baseline",
                            "label": f"Static Comfort Space {args.static_size:.2f} m (baseline)"},
               "comfort_space": {"policy": "static", "static_radius": round(args.static_size, 4)}},
              out)
    print(f"wrote {p.relative_to(PROJECT_ROOT)}")

    p = write("b3o_initial", "B3-O Initial (literature-anchored engineering parameters)",
              "# The proposed method as it entered Stage 1: configs/common.yaml\n"
              "# comfort_space.directional unscaled (moving front 1.20 m at 1.0 m/s,\n"
              "# engaged F0.80/S0.70/R0.60, stationary F0.80/S0.90/R1.05).",
              {"scenario": {"name": "b3o_initial",
                            "label": "B3-O Dynamic Comfort Space, initial parameters"},
               "comfort_space": {"policy": "state_directional",
                                 "aisle_scaling": {"enabled": False}}},
              out)
    print(f"wrote {p.relative_to(PROJECT_ROOT)}")

    if args.r_opt is not None and args.params:
        ap.error("give --r-opt or --params, not both")
    if args.r_opt is not None:
        cs = {"policy": "state_directional",
              "aisle_scaling": {"enabled": True, "target_size_m": round(args.r_opt, 4),
                                "floor_m": 0.0}}
        how = (f"# The Stage 2 result expressed as a size: the whole B3-O geometry\n"
               f"# scaled so the moving front at the reference speed is {args.r_opt:.2f} m\n"
               f"# (ratios and state relations unchanged). R_opt from Stage 2.")
        label = f"B3-O Dynamic Comfort Space, optimized (R_opt {args.r_opt:.2f} m)"
    elif args.params:
        given = load_with_base(args.params)
        block = given.get("comfort_space", given)
        if "directional" not in block:
            print(f"[ERROR] {args.params} has no `directional:` block", file=sys.stderr)
            return 2
        cs = {"policy": "state_directional", "aisle_scaling": {"enabled": False},
              "directional": block["directional"]}
        if "min_radius" in block:
            cs["min_radius"] = block["min_radius"]
        how = (f"# The Stage 2 calibrated parameter set, copied from {args.params}:\n"
               "# a directional block that replaces configs/common.yaml's.")
        label = "B3-O Dynamic Comfort Space, optimized (Stage 2 calibrated parameters)"
    else:
        cs = {"policy": "state_directional",
              "aisle_scaling": {"enabled": True, "target_size_m": None, "floor_m": 0.0}}
        how = ("# TEMPLATE. target_size_m is null until Stage 2 has produced R_opt.\n"
               "# scripts/stage3_run.sh refuses this condition while it is null.\n"
               "# Fill it with --r-opt, or give a calibrated block with --params.")
        label = "B3-O Dynamic Comfort Space, optimized (TODO: R_opt from Stage 2)"
    p = write("b3o_optimized", "B3-O Optimized (Stage 2 calibrated)", how,
              {"scenario": {"name": "b3o_optimized", "label": label}, "comfort_space": cs}, out)
    print(f"wrote {p.relative_to(PROJECT_ROOT)}"
          + ("  (TEMPLATE: target_size_m null)" if args.r_opt is None and not args.params else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
